"""Regenerate the Python and TypeScript contract code from contracts/schemas/.

Run it from the repository root:

    uv run tools/gen_contracts.py

The JSON Schemas in `contracts/schemas/` are the single source of truth. This
tool only transforms them into what the two generators can consume, and it is
deterministic: running it twice on an unchanged tree writes identical files.

* Python: the eight schemas are bundled into one temporary document (the
  absolute `https://bgsim.local/schemas/...` references are rewritten to local
  `#/$defs/...` ones) and passed to `datamodel-code-generator`, which writes
  `backend/src/bgsim_server/contracts.py`.
* TypeScript: every schema is staged with file-relative `$ref`s so that
  `json-schema-to-typescript` can resolve them from disk; it writes
  `web/src/contracts/<name>.ts`, and `web/src/contracts/index.ts` is written
  here as well.

Both generators live in their own project (`backend/`, `web/`), which is why
they are invoked through `uv run --directory backend` and `node` with a
`createRequire` anchored in `web/package.json`.
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SCHEMA_DIR = REPO / "contracts" / "schemas"
BACKEND_DIR = REPO / "backend"
WEB_DIR = REPO / "web"
PY_OUT = BACKEND_DIR / "src" / "bgsim_server" / "contracts.py"
TS_OUT_DIR = WEB_DIR / "src" / "contracts"
ID_PREFIX = "https://bgsim.local/schemas/"

PY_HEADER = (
    "# Generated by tools/gen_contracts.py from contracts/schemas/*.schema.json.\n"
    "# Do not edit by hand: change the schema and regenerate."
)
TS_BANNER = (
    "/* Generated by tools/gen_contracts.py from contracts/schemas/*.schema.json.\n"
    " * Do not edit by hand: change the schema and regenerate. */"
)


def die(message: str) -> None:
    print(f"gen_contracts: error: {message}", file=sys.stderr)
    raise SystemExit(1)


def load_schemas() -> dict[str, dict]:
    """Read every schema, keyed by base name (the file name without .schema.json)."""
    schemas: dict[str, dict] = {}
    for path in sorted(SCHEMA_DIR.glob("*.schema.json")):
        base = path.name[: -len(".schema.json")]
        doc = json.loads(path.read_text(encoding="utf-8"))
        if doc.get("$id") != f"{ID_PREFIX}{path.name}":
            die(f"{path.name}: $id must be {ID_PREFIX}{path.name}")
        schemas[base] = doc
    if not schemas:
        die(f"no schemas found in {SCHEMA_DIR}")
    return schemas


def type_names(schemas: dict[str, dict]) -> dict[tuple[str, str | None], str]:
    """Assign one globally unique type name to every schema root and $defs entry."""
    names: dict[tuple[str, str | None], str] = {}
    seen: dict[str, tuple[str, str | None]] = {}
    for base, doc in schemas.items():
        entries: list[tuple[str | None, dict]] = [(None, doc)]
        for key, entry in (doc.get("$defs") or {}).items():
            entries.append((key, entry))
        for key, entry in entries:
            title = entry.get("title")
            if title:
                name = title
            elif key is None:
                name = base.title()
            else:
                name = base.title() + key[0].upper() + key[1:]
            if name in seen:
                die(f"type name {name!r} is used by both {seen[name]} and {(base, key)}")
            seen[name] = (base, key)
            names[(base, key)] = name
    return names


def rewrite_refs(node, base: str, names: dict[tuple[str, str | None], str], root: bool = False):
    """Copy a schema, rewriting every $ref to a local #/$defs/<Name> pointer."""
    if isinstance(node, list):
        return [rewrite_refs(item, base, names) for item in node]
    if not isinstance(node, dict):
        return node
    out = {}
    for key, value in node.items():
        if key in ("$id", "$schema"):
            continue
        if key == "$defs":
            if root:
                continue  # the root's own $defs are bundled as separate entries
            die(f"{base}: nested $defs are not supported")
        if key == "$ref" and isinstance(value, str):
            out[key] = rewrite_ref(value, base, names)
        else:
            out[key] = rewrite_refs(value, base, names)
    return out


def rewrite_ref(ref: str, base: str, names: dict[tuple[str, str | None], str]) -> str:
    target, _, fragment = ref.partition("#")
    if target.startswith(ID_PREFIX):
        other = target[len(ID_PREFIX) :]
        if not other.endswith(".schema.json"):
            die(f"{base}: cannot resolve $ref {ref}")
        other_base = other[: -len(".schema.json")]
        if other_base not in {b for b, _ in names}:
            die(f"{base}: $ref to unknown schema {target}")
    else:
        other_base = base
    if fragment in ("", "/"):
        key = None
    elif fragment.startswith("/$defs/"):
        key = fragment[len("/$defs/") :]
        if "/" in key:
            die(f"{base}: nested $def pointer {ref}")
    else:
        die(f"{base}: unsupported $ref fragment in {ref}")
    if (other_base, key) not in names:
        die(f"{base}: $ref {ref} does not point at a named definition")
    return f"#/$defs/{names[(other_base, key)]}"


def relative_refs(node):
    """Copy a schema, turning absolute $id references into sibling-file ones."""
    if isinstance(node, list):
        return [relative_refs(item) for item in node]
    if not isinstance(node, dict):
        return node
    out = {}
    for key, value in node.items():
        if key == "$ref" and isinstance(value, str) and value.startswith(ID_PREFIX):
            out[key] = value[len(ID_PREFIX) :]
        else:
            out[key] = relative_refs(value)
    return out


def write_json(path: Path, doc) -> None:
    path.write_text(json.dumps(doc, indent=2) + "\n", encoding="utf-8", newline="\n")


def run(args: list[str], cwd: Path) -> None:
    print("  $ " + " ".join(str(a) for a in args))
    proc = subprocess.run(args, cwd=str(cwd))
    if proc.returncode != 0:
        die(f"command failed with exit code {proc.returncode}: {' '.join(str(a) for a in args)}")


def generate_python(schemas: dict[str, dict], names: dict[tuple[str, str | None], str], stage: Path) -> None:
    defs = {}
    for base, doc in schemas.items():
        defs[names[(base, None)]] = rewrite_refs(doc, base, names, root=True)
        for key, entry in (doc.get("$defs") or {}).items():
            defs[names[(base, key)]] = rewrite_refs(entry, base, names)
    bundle = {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "title": "Contracts",
        "description": "Bundle of contracts/schemas/*.schema.json for code generation only.",
        "anyOf": [{"$ref": f"#/$defs/{names[(base, None)]}"} for base in schemas],
        "$defs": defs,
    }
    bundle_path = stage / "contracts.bundle.json"
    write_json(bundle_path, bundle)
    PY_OUT.parent.mkdir(parents=True, exist_ok=True)
    run(
        [
            "uv",
            "run",
            "--directory",
            str(BACKEND_DIR),
            "datamodel-codegen",
            "--input",
            str(bundle_path),
            "--output",
            str(PY_OUT),
            "--input-file-type",
            "jsonschema",
            "--output-model-type",
            "pydantic_v2.BaseModel",
            "--target-python-version",
            "3.13",
            "--disable-timestamp",
            "--use-title-as-name",
            "--custom-file-header",
            PY_HEADER,
            "--custom-file-header-mode",
            "replace",
        ],
        cwd=REPO,
    )


def generate_typescript(schemas: dict[str, dict], names: dict[tuple[str, str | None], str], stage: Path) -> None:
    staged: dict[str, Path] = {}
    for base, doc in schemas.items():
        path = stage / f"{base}.schema.json"
        write_json(path, relative_refs(doc))
        staged[base] = path

    helper = stage / "gen_ts.mjs"
    helper.write_text(TS_HELPER, encoding="utf-8", newline="\n")
    TS_OUT_DIR.mkdir(parents=True, exist_ok=True)
    files = {base: TS_OUT_DIR / f"{base}.ts" for base in schemas}
    for base in sorted(schemas):
        run(
            [
                "node",
                str(helper),
                (WEB_DIR / "package.json").as_uri(),
                str(staged[base]),
                str(stage),
                str(files[base]),
                TS_BANNER,
            ],
            cwd=REPO,
        )

    emitted = {base: re.findall(r"^export (?:interface|type) (\w+)", path.read_text(encoding="utf-8"), re.M) for base, path in files.items()}
    index = [
        "/* Generated by tools/gen_contracts.py from contracts/schemas/*.schema.json.",
        " * Do not edit by hand: change the schema and regenerate.",
        " *",
        " * Every schema is re-exported as a namespace, and every type it defines is",
        " * re-exported by name from the file that owns it. Types pulled in through a",
        " * cross-schema $ref are inlined in each file that needs them, so the by-name",
        " * exports below are the canonical ones.",
        " */",
        "",
    ]
    for base in sorted(schemas):
        parts = base.split("-")
        ns = parts[0] + "".join(p.title() for p in parts[1:])
        index.append(f'export * as {ns} from "./{base}";')
    index.append("")
    for base in sorted(schemas):
        owned = [name for (owner, _), name in names.items() if owner == base and name in emitted[base]]
        for name in sorted(owned):
            index.append(f'export type {{ {name} }} from "./{base}";')
    index.append("")
    (TS_OUT_DIR / "index.ts").write_text("\n".join(index), encoding="utf-8", newline="\n")


TS_HELPER = r"""
import { createRequire } from "node:module";
import { readFileSync, writeFileSync } from "node:fs";

const [packageJson, schemaPath, cwd, outPath, banner] = process.argv.slice(2);
const require = createRequire(packageJson);
const jstt = require("json-schema-to-typescript");

const schema = JSON.parse(readFileSync(schemaPath, "utf8"));
const output = await jstt.compile(schema, schema.title ?? "Schema", {
  cwd,
  bannerComment: banner,
  additionalProperties: false,
  declareExternallyReferenced: true,
  unreachableDefinitions: false,
  format: true,
});
writeFileSync(outPath, output);
console.log(`  wrote ${outPath}`);
"""


def main() -> int:
    schemas = load_schemas()
    names = type_names(schemas)
    roots = [names[(base, None)] for base in schemas]
    with tempfile.TemporaryDirectory(prefix="bgsim-contracts-") as tmp:
        stage = Path(tmp)
        print("Python ->", PY_OUT.relative_to(REPO))
        generate_python(schemas, names, stage)
        print("TypeScript ->", TS_OUT_DIR.relative_to(REPO))
        generate_typescript(schemas, names, stage)
    print(
        f"generated {len(roots)} schemas ({', '.join(roots)}) into "
        f"{PY_OUT.relative_to(REPO)} and {TS_OUT_DIR.relative_to(REPO)}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
