# Writes `contracts/fixtures/modes/mode_shapes.json`: the flexible-beam mode shapes of
# `BGSim.Mech` (src/mech/modes.jl) at s/L = 0, 0.25, 0.5, 0.75, 1 for n = 1..3 of every
# family (bending phi, torsion psi) and basis, so the 3D viewer's renderer of the deformed
# beam can be cross-checked against the Julia side. `test/test_flex_modes.jl` asserts that
# the committed file matches these functions.
#
#     julia --project=julia/BGSim tools/gen_mode_shapes.jl
using BGSim
using BGSim.Mech
import JSON3

const XI = [0.0, 0.25, 0.5, 0.75, 1.0]

function mode_shape_fixture()
    entry(basis) = (;
            lambda = [Mech.beam_lambda(basis, n) for n in 1:3],
            sigma = [Mech.beam_sigma(basis, n) for n in 1:3],
            torsion_k = [Mech.torsion_k(basis, n) for n in 1:3],
            phi = [[Mech.beam_phi(basis, n, x) for x in XI] for n in 1:3],
            dphi = [[Mech.beam_dphi(basis, n, x) for x in XI] for n in 1:3],
            psi = [[Mech.torsion_psi(basis, n, x) for x in XI] for n in 1:3],
        )
    names = Tuple(Symbol.(Mech.BEAM_BASES))
    bases = NamedTuple{names}(Tuple(entry(k - 1) for k in eachindex(names)))
    comment = "Flexible beam mode shapes (julia/BGSim/src/mech/modes.jl), generated by " *
              "tools/gen_mode_shapes.jl. phi[n][k] / psi[n][k] is mode n+1 at s/L = xi[k]; " *
              "dphi is d(phi)/d(s/L). Normalisation (1/L) int phi^2 ds = 1. Bending: " *
              "w(s) = sum phi_n eta_n along local y or z; torsion: theta(s) = sum psi_n eta_n " *
              "about local x."
    return NamedTuple{(Symbol("\$comment"), :xi, :bases)}((comment, XI, bases))
end

if abspath(PROGRAM_FILE) == @__FILE__
    out = joinpath(@__DIR__, "..", "contracts", "fixtures", "modes", "mode_shapes.json")
    mkpath(dirname(out))
    open(out, "w") do io
        JSON3.pretty(io, mode_shape_fixture())
        println(io)
    end
    println("wrote ", normpath(out))
end
