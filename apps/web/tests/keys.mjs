// Flies with real key presses: pull, roll, throttle, pause, restart. node tests/keys.mjs [out.png]
import { chromium } from "playwright";
const port = process.env.GAMES_PORT ?? "8831";
const browser = await chromium.launch({ headless: true, args: ["--use-angle=d3d11", "--ignore-gpu-blocklist", "--enable-gpu", "--enable-unsafe-swiftshader"] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const logs = [];
page.on("console", (m) => { if (["error", "warning"].includes(m.type())) logs.push(m.text().slice(0, 400)); });
page.on("pageerror", (e) => logs.push("PAGEERROR " + e.message.slice(0, 400)));
await page.goto(process.env.GAME_URL ?? `http://127.0.0.1:${port}/${process.env.GAME_PATH ?? "f16/"}?grid=1024`);
await page.waitForFunction(() => window.ready, null, { timeout: 90000 });
const read = () => page.evaluate(() => { const f = game.flight; return { ...game.state(), alt: Math.round(f.get("alt_m")), phi: Math.round(f.get("phi_deg")), gamma: +f.get("gamma_deg").toFixed(1), nz: +f.get("nz_g").toFixed(1), throttle: +f.u[3].toFixed(2), power: Math.round(f.get("power_pct")) }; });
const check = (name, ok, detail) => { console.log(`${ok ? "ok  " : "FAIL"} ${name} ${JSON.stringify(detail)}`); if (!ok) process.exitCode = 1; };
await page.click("#fly");
await page.waitForTimeout(800);
const level = await read();
check("flying after Fly", level.phase === "flying" && !level.crashed, level);
await page.keyboard.down("ArrowDown");
await page.waitForTimeout(1400);
await page.keyboard.up("ArrowDown");
const pulled = await read();
check("down arrow pulls", pulled.gamma > level.gamma + 3 && pulled.nz > 1.2, pulled);
await page.waitForTimeout(1500);
await page.keyboard.down("ArrowRight");
await page.waitForTimeout(700);
await page.keyboard.up("ArrowRight");
const rolled = await read();
check("right arrow rolls right", rolled.phi > 15, rolled);
await page.keyboard.down("PageUp");
await page.waitForTimeout(2600);
await page.keyboard.up("PageUp");
const hot = await read();
check("page up opens the throttle", hot.throttle > 0.9, hot);
await page.waitForTimeout(2500);
const burner = await read();
check("afterburner lights", burner.power > 55, burner);
await page.screenshot({ path: process.argv[2] ?? "keys.png" });
await page.keyboard.press("KeyC");
check("C changes the view", (await read()).view === "cockpit", {});
await page.keyboard.press("KeyC");
await page.keyboard.press("KeyC");
await page.keyboard.press("KeyP");
const paused = await read();
await page.waitForTimeout(600);
const still = await read();
check("P pauses", paused.phase === "paused" && paused.time === still.time, still);
await page.keyboard.press("KeyP");
await page.waitForTimeout(300);
check("P resumes", (await read()).phase === "flying", {});
await page.keyboard.press("KeyR");
await page.waitForTimeout(300);
const fresh = await read();
check("R restarts", fresh.time < 1, fresh);
console.log(logs.slice(0, 6).join("\n"));
await browser.close();
