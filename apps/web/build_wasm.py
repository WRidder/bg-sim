"""Turn a bg-sim FMU into what a browser game imports: one TypeScript module with the Wasm inside.

    uv run build_wasm.py f16 ../f16-sim/build/f16_sim.fmu

compiles the C sources every FMU carries with the shim in `shim/`, and writes
`src/<game>/model.gen.ts`: the Wasm as base64, the GUID, the communication step and the value
references by name. Embedding it means the static site and the single HTML file load the model the
same way, and it needs no fetch, which a page opened from file:// could not do.

Zig is the C compiler because it comes through uv, pinned above, with nothing else to install.
The same -O2 -fno-math-errno and no -ffast-math as the native export (plan/EXPORT_PLAN.md, D-EX14).
"""

from __future__ import annotations

import base64
import json
import re
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path

HERE = Path(__file__).resolve().parent


def compile_wasm(sources: Path, out: Path) -> None:
    files = sorted(sources.glob("*.c"))
    command = [
        sys.executable, "-m", "ziglang", "cc", "-target", "wasm32-wasi", "-mexec-model=reactor", "-std=c11",
        "-O2", "-fno-math-errno", "-g0", "-Wl,--strip-all", f"-I{sources}", str(HERE / "shim" / "sim_shim.c"),
        *map(str, files), "-lm", "-o", str(out),
    ]
    subprocess.run(command, check=True)


def main() -> None:
    game, fmu = sys.argv[1], Path(sys.argv[2])
    with tempfile.TemporaryDirectory() as tmp, zipfile.ZipFile(fmu) as archive:
        archive.extractall(tmp)
        root = Path(tmp)
        xml = (root / "modelDescription.xml").read_text(encoding="utf-8")
        wasm = root / "model.wasm"
        compile_wasm(root / "sources", wasm)
        data = wasm.read_bytes()
    guid = re.search(r'guid="([^"]+)"', xml).group(1)
    step = float(re.search(r'stepSize="([^"]+)"', xml).group(1))
    refs = {m[1]: int(m[2]) for m in re.finditer(r'<ScalarVariable name="([^"]+)" valueReference="(\d+)"', xml)}
    target = HERE / "src" / game / "model.gen.ts"
    target.write_text(
        "// Generated by build_wasm.py from " + fmu.name + ". Do not edit.\n"
        'import type { FmuModel } from "../engine/fmu";\n\n'
        "export const model: FmuModel = "
        + json.dumps({"guid": guid, "step": step, "refs": refs, "wasm": base64.b64encode(data).decode()})
        + ";\n",
        encoding="utf-8", newline="\n",
    )
    print(f"{target.relative_to(HERE)}: {len(data)} bytes of Wasm, {len(refs)} variables, step {step}")


if __name__ == "__main__":
    main()
