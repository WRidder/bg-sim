"""Turn a bg-sim FMU into what a browser game imports: one TypeScript module with the Wasm inside.

    uv run build_wasm.py f16 ../f16-sim/build/f16_sim.fmu
    uv run build_wasm.py cars ../car-sim/build/buggy_sim.fmu buggy.gen.ts

compiles the C sources every FMU carries with the shim in `shim/`, and writes
`src/<game>/model.gen.ts` (or the name given third, for a game with two models): the Wasm as base64, the GUID, the communication step and the value
references by name. Embedding it means the static site and the single HTML file load the model the
same way, and it needs no fetch, which a page opened from file:// could not do.

Zig is the C compiler because it comes through uv, pinned above, with nothing else to install.
The same -O2 -fno-math-errno and no -ffast-math as the native export (plan/EXPORT_PLAN.md, D-EX14).
"""

from __future__ import annotations

import base64
import json
import re
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
import zipfile
from pathlib import Path

HERE = Path(__file__).resolve().parent


def compile_wasm(sources: Path, out: Path) -> None:
    files = sorted(sources.glob("*.c"))
    command = [
        sys.executable, "-m", "ziglang", "cc", "-target", "wasm32-wasi", "-mexec-model=reactor", "-std=c11",
        "-O2", "-fno-math-errno", "-g0", "-Wl,--strip-all", f"-I{sources}", str(HERE / "shim" / "sim_shim.c"),
        *map(str, files), "-lm", "-o", str(out),
    ]
    subprocess.run(command, check=True)


def parameters(xml: str) -> list[dict]:
    """What the player may set: every FMU parameter with its start value, range, unit and description."""
    out = []
    for variable in ET.fromstring(xml).iter("ScalarVariable"):
        real = variable.find("Real")
        if variable.get("causality") != "parameter" or real is None or real.get("start") is None:
            continue
        item = {"name": variable.get("name"), "start": float(real.get("start"))}
        item |= {k: float(real.get(k)) for k in ("min", "max") if real.get(k) is not None}
        item |= {"unit": real.get("unit")} if real.get("unit") else {}
        item |= {"description": variable.get("description")} if variable.get("description") else {}
        out.append(item)
    return out


def main() -> None:
    game, fmu = sys.argv[1], Path(sys.argv[2])
    name = sys.argv[3] if len(sys.argv) > 3 else "model.gen.ts"
    with tempfile.TemporaryDirectory() as tmp, zipfile.ZipFile(fmu) as archive:
        archive.extractall(tmp)
        root = Path(tmp)
        xml = (root / "modelDescription.xml").read_text(encoding="utf-8")
        wasm = root / "model.wasm"
        compile_wasm(root / "sources", wasm)
        data = wasm.read_bytes()
    guid = re.search(r'guid="([^"]+)"', xml).group(1)
    model_name = re.search(r'modelName="([^"]+)"', xml).group(1)
    params = parameters(xml)
    step = float(re.search(r'stepSize="([^"]+)"', xml).group(1))
    refs = {m[1]: int(m[2]) for m in re.finditer(r'<ScalarVariable name="([^"]+)" valueReference="(\d+)"', xml)}
    target = HERE / "src" / game / name
    target.write_text(
        "// Generated by build_wasm.py from " + fmu.name + ". Do not edit.\n"
        'import type { FmuModel } from "../engine/fmu";\n\n'
        "export const model: FmuModel = "
        + json.dumps({"name": model_name, "guid": guid, "step": step, "refs": refs, "params": params, "wasm": base64.b64encode(data).decode()})
        + ";\n",
        encoding="utf-8", newline="\n",
    )
    print(f"{target.relative_to(HERE)}: {len(data)} bytes of Wasm, {len(refs)} variables, {len(params)} parameters, step {step}")


if __name__ == "__main__":
    main()
