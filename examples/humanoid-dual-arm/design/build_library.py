"""Write the project blocks of `humanoid-dual-arm` (`library/*.jl`).

    uv run examples/humanoid-dual-arm/design/build_library.py

* `ObjectTrajectory`  the 1 kHz task layer: the commanded pose of the shared object (start pose,
                      quintic move to the dashboard pose, elbow-bias ramp), the 6-DOF switch, and
                      the object pose in the bg-sim world for the 3D view.
* `ArmIK`             the 1 kHz IK of one arm: the page's damped least squares with a null-space
                      pull toward home (one iteration per tick, warm-started), written as scalar
                      code (generated below; `srs.ik_step(..., jac="analytic")` is its twin).
* `ArmServo`          the 1 kHz joint servo of one arm: PID with reference-rate feedforward, an
                      anti-windup clamp and the torque limits.
* `PoseError`         the position [mm] and angle [deg] between two poses (continuous, observed).
* `GraspLoad`         force [N] and moment [N m] carried by one compliant grasp (continuous).

The IK and the servo are generated because the language has no `\\` for matrices (see README):
the 6x6 solves are written out as Cholesky factorisations.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np

import srs

ROOT = Path(__file__).resolve().parent.parent
LIB = ROOT / "library"


def num(x: float) -> str:
    return repr(float(x))


def vec(v) -> str:
    return "[" + ", ".join(num(x) for x in v) + "]"


def mat(m) -> str:
    return "[" + "; ".join(" ".join(num(x) for x in row) for row in m) + "]"


# ===================================================================== ObjectTrajectory


def object_trajectory(dz) -> str:
    p0, r0 = dz.OBJ_START
    p1, r1 = srs.OBJ_DEFAULT
    T = dz.TIMING
    g0 = dz.object_pose_world(p0, r0)
    return f"""@block ObjectTrajectory begin
    # 1 kHz task layer of the bimanual hold (sampled firmware). Generated by
    # design/build_library.py from design/humanoid.py.
    #
    # The shared object starts at the pose both arm variants hold (p0, rpy0), waits t_settle,
    # moves rest to rest to the commanded pose (x, y, z, roll, pitch, yaw) in t_move with the
    # quintic s = tau^3 (10 - 15 tau + 6 tau^2), dwells t_dwell and then ramps the elbow bias from
    # 0 to `bias` with the same quintic in t_bias. Page frame (x right = the robot's left, y up,
    # z forward), angles in degrees, the page's rotation R = Ry(yaw) Rx(pitch) Rz(roll).
    #
    # `obj` = (x, y, z, roll, pitch, yaw, elbow bias, J5 lock) is the input of the four ArmIK
    # blocks. `g` is the commanded object pose in the bg-sim world (Z up, the robot faces +X:
    # world = (page z, page x, page y + z0), quaternion first, the D-MB6 chart), `gi` the same
    # pose shifted by `dy` for the ideal-SRS pair drawn beside the robot.
    @parameters begin
        x::Real = {num(p1[0])}, [unit = "m", description = "Commanded object x (page frame: right, the robot's left)"]
        y::Real = {num(p1[1])}, [unit = "m", description = "Commanded object y (up)"]
        z::Real = {num(p1[2])}, [unit = "m", description = "Commanded object z (forward)"]
        roll::Real = {num(r1[0])}, [description = "Commanded object roll (about the page z)"]
        pitch::Real = {num(r1[1])}, [description = "Commanded object pitch (about the page x)"]
        yaw::Real = {num(r1[2])}, [description = "Commanded object yaw (about the page y, vertical)"]
        bias::Real = {num(dz.BIAS)}, [description = "Elbow bias: added to the shoulder-yaw home of the null-space pull (mirrored)"]
        dof6::Bool = false, [description = "6-DOF arms: lock J5 (forearm yaw) at zero"]
        x0::Real = {num(p0[0])}, [unit = "m", description = "Start object x"]
        y0::Real = {num(p0[1])}, [unit = "m", description = "Start object y"]
        z0::Real = {num(p0[2])}, [unit = "m", description = "Start object z"]
        roll0::Real = {num(r0[0])}, [description = "Start object roll"]
        pitch0::Real = {num(r0[1])}, [description = "Start object pitch"]
        yaw0::Real = {num(r0[2])}, [description = "Start object yaw"]
        t_settle::Real = {num(T["settle"])}, [unit = "s", min = 0, description = "Hold at the start pose"]
        t_move::Real = {num(T["move"])}, [unit = "s", min = 1.0e-3, description = "Duration of the move to the commanded pose"]
        t_dwell::Real = {num(T["dwell"])}, [unit = "s", min = 0, description = "Dwell before the elbow-bias ramp"]
        t_bias::Real = {num(T["bias"])}, [unit = "s", min = 1.0e-3, description = "Duration of the elbow-bias ramp"]
        zw::Real = {num(srs.Z0)}, [unit = "m", description = "Height of the page origin in the world"]
        dy::Real = {num(dz.GHOST_DY)}, [unit = "m", description = "World y shift of the ideal-SRS pair"]
    end
    @outputs begin
        obj::Vec{{8}} = {vec([*p0, *r0, 0.0, 0.0])}
        g::Vec{{7}} = {vec(g0)}
        gi::Vec{{7}} = {vec([*g0[:5], g0[5] + dz.GHOST_DY, g0[6]])}
        px::Real = {num(p0[0])}, [unit = "m"]
        py::Real = {num(p0[1])}, [unit = "m"]
        pz::Real = {num(p0[2])}, [unit = "m"]
        elbow_bias::Real = 0.0, [description = "Elbow bias [deg]"]
        lock::Real = 0.0, [unit = "1", description = "1 when J5 is locked (6-DOF arms)"]
        phase::Real = 0.0, [unit = "1", description = "0 settle, 1 move, 2 dwell, 3 bias ramp, 4 hold"]
    end
    @discrete Ts = {num(dz.TS)} begin
        ta = t_settle
        tb = ta + t_move
        tc = tb + t_dwell
        td = tc + t_bias
        tau = clamp((t - ta) / t_move, 0.0, 1.0)
        s = tau * tau * tau * (10.0 - 15.0 * tau + 6.0 * tau * tau)
        taub = clamp((t - tc) / t_bias, 0.0, 1.0)
        sb = taub * taub * taub * (10.0 - 15.0 * taub + 6.0 * taub * taub)
        ox = x0 + (x - x0) * s
        oy = y0 + (y - y0) * s
        oz = z0 + (z - z0) * s
        orl = roll0 + (roll - roll0) * s
        opi = pitch0 + (pitch - pitch0) * s
        oya = yaw0 + (yaw - yaw0) * s
        ob = bias * sb
        lk = 0.0
        if dof6
            lk = 1.0
        end
        obj[1] = ox
        obj[2] = oy
        obj[3] = oz
        obj[4] = orl
        obj[5] = opi
        obj[6] = oya
        obj[7] = ob
        obj[8] = lk
        # world quaternion: q_P (x) qy(yaw) (x) qx(pitch) (x) qz(roll), q_P = (1/2)(1, 1, 1, 1) the
        # rotation page -> world (a turn of 120 deg about (1, 1, 1))
        cy = cos(0.5 * oya * deg)
        sy = sin(0.5 * oya * deg)
        cp = cos(0.5 * opi * deg)
        sp = sin(0.5 * opi * deg)
        cr = cos(0.5 * orl * deg)
        sr = sin(0.5 * orl * deg)
        # a = qy (x) qx = (cy cp, cy sp, sy cp, -sy sp)
        aw = cy * cp
        ax = cy * sp
        ay = sy * cp
        az = -sy * sp
        # b = a (x) qz(roll), qz = (cr, 0, 0, sr)
        bw = aw * cr - az * sr
        bx = ax * cr + ay * sr
        by = ay * cr - ax * sr
        bz = az * cr + aw * sr
        # q = q_P (x) b
        g[1] = 0.5 * (bw - bx - by - bz)
        g[2] = 0.5 * (bw + bx - by + bz)
        g[3] = 0.5 * (bw + bx + by - bz)
        g[4] = 0.5 * (bw - bx + by + bz)
        g[5] = oz
        g[6] = ox
        g[7] = oy + zw
        gi[1] = g[1]
        gi[2] = g[2]
        gi[3] = g[3]
        gi[4] = g[4]
        gi[5] = oz
        gi[6] = ox + dy
        gi[7] = oy + zw
        px = ox
        py = oy
        pz = oz
        elbow_bias = ob
        lock = lk
        ph = 0.0
        if t >= ta
            ph = 1.0
        end
        if t >= tb
            ph = 2.0
        end
        if t >= tc
            ph = 3.0
        end
        if t >= td
            ph = 4.0
        end
        phase = ph
    end
end
"""


# ===================================================================== ArmIK


class Code:
    def __init__(self, indent: str = "        ") -> None:
        self.lines: list[str] = []
        self.indent = indent

    def __call__(self, text: str = "") -> None:
        self.lines.append(self.indent + text if text else "")

    def comment(self, text: str) -> None:
        self(f"# {text}")


def rot_columns(code: Code, i: int, ax: str, prev: str, new: str, th: str) -> None:
    """new = prev * Rot_ax(th), column by column (prev, new: name prefixes `R<i>_<row><col>`)."""
    code(f"c{i} = cos({th})")
    code(f"s{i} = sin({th})")
    for r in range(1, 4):
        a = [f"{prev}_{r}{k}" for k in range(1, 4)]
        if ax == "x":
            cols = [a[0], f"c{i} * {a[1]} + s{i} * {a[2]}", f"c{i} * {a[2]} - s{i} * {a[1]}"]
        elif ax == "y":
            cols = [f"c{i} * {a[0]} - s{i} * {a[2]}", a[1], f"s{i} * {a[0]} + c{i} * {a[2]}"]
        else:
            cols = [f"c{i} * {a[0]} + s{i} * {a[1]}", f"c{i} * {a[1]} - s{i} * {a[0]}", a[2]]
        for k in range(3):
            code(f"{new}_{r}{k + 1} = {cols[k]}")


def cross(a: list[str], b: list[str]) -> list[str]:
    return [
        f"({a[1]} * {b[2]} - {a[2]} * {b[1]})",
        f"({a[2]} * {b[0]} - {a[0]} * {b[2]})",
        f"({a[0]} * {b[1]} - {a[1]} * {b[0]})",
    ]


def cholesky_solve(code: Code, a: str, lam: str, rhs: list[str], out: str, tag: str) -> None:
    """out_k = solve(A + lam I, rhs) for the symmetric 6x6 A (`{a}<r><c>`, r <= c)."""
    n = 6

    def aa(r, c):
        r, c = min(r, c), max(r, c)
        return f"{a}{r}{c}"

    for j in range(1, n + 1):
        s = " - ".join([f"{aa(j, j)} + {lam}"] + [f"L{tag}{j}{k} * L{tag}{j}{k}" for k in range(1, j)])
        code(f"L{tag}{j}{j} = sqrt({s})")
        for i in range(j + 1, n + 1):
            s = " - ".join([aa(i, j)] + [f"L{tag}{i}{k} * L{tag}{j}{k}" for k in range(1, j)])
            code(f"L{tag}{i}{j} = ({s}) / L{tag}{j}{j}")
    for i in range(1, n + 1):
        s = " - ".join([rhs[i - 1]] + [f"L{tag}{i}{k} * w{tag}{k}" for k in range(1, i)])
        code(f"w{tag}{i} = ({s}) / L{tag}{i}{i}")
    for i in range(n, 0, -1):
        s = " - ".join([f"w{tag}{i}"] + [f"L{tag}{k}{i} * {out}{k}" for k in range(i + 1, n + 1)])
        code(f"{out}{i} = ({s}) / L{tag}{i}{i}")


def arm_ik() -> str:
    q0 = srs.HOME
    code = Code()
    c = code
    c.comment("start: the configuration both variants hold (q0, the instance's start posture)")
    c("if init < 0.5")
    for k in range(1, 8):
        c(f"    q{k} = q0[{k}]")
    c("    init = 1.0")
    c("end")
    c("lockf = 0.0")
    c("if obj[8] > 0.5")
    c("    lockf = 1.0")
    c("end")
    c("act5 = 1.0 - lockf")
    c("q5 = act5 * q5")
    c.comment("object rotation R = Ry(yaw) Rx(pitch) Rz(roll) (page frame) and the grasp target")
    c("cr = cos(obj[4] * deg)")
    c("sr = sin(obj[4] * deg)")
    c("cp = cos(obj[5] * deg)")
    c("sp = sin(obj[5] * deg)")
    c("cy = cos(obj[6] * deg)")
    c("sy = sin(obj[6] * deg)")
    # Ry Rx = [[cy, sy sp, sy cp], [0, cp, -sp], [-sy, cy sp, cy cp]]; times Rz(roll)
    c("O_11 = cy * cr + sy * sp * sr")
    c("O_12 = -cy * sr + sy * sp * cr")
    c("O_13 = sy * cp")
    c("O_21 = cp * sr")
    c("O_22 = cp * cr")
    c("O_23 = -sp")
    c("O_31 = -sy * cr + cy * sp * sr")
    c("O_32 = sy * sr + cy * sp * cr")
    c("O_33 = cy * cp")
    c.comment("hand target: at (s hb, 0, 0) of the object, columns R (0, s, 0), R (0, 0, -1), R (-s, 0, 0)")
    for r in range(1, 4):
        c(f"tp{r} = obj[{r}] + s * hb * O_{r}1")
        c(f"T1_{r} = s * O_{r}2")
        c(f"T2_{r} = -O_{r}3")
        c(f"T3_{r} = -s * O_{r}1")
    c.comment("forward kinematics: joint origins o<k>, world axes u<k> (direction of +q), hand R7, p7")
    c("R0_11 = 1.0")
    c("R0_12 = 0.0")
    c("R0_13 = 0.0")
    c("R0_21 = 0.0")
    c("R0_22 = 1.0")
    c("R0_23 = 0.0")
    c("R0_31 = 0.0")
    c("R0_32 = 0.0")
    c("R0_33 = 1.0")
    c("p0_1 = s * sx")
    c("p0_2 = sy0")
    c("p0_3 = 0.0")
    for i in range(1, 8):
        ax = srs.AX[i - 1]
        col = "xyz".index(ax) + 1
        cs = "-1.0" if srs.PITCH[i - 1] else "s"
        c.comment(f"J{i} {srs.NAMES[i - 1]}: about the page {ax}, by {'-q' if srs.PITCH[i - 1] else 's q'}")
        for r in range(1, 4):
            c(f"o{i}_{r} = p{i - 1}_{r}")
            c(f"u{i}_{r} = {cs} * R{i - 1}_{r}{col}")
        rot_columns(code, i, ax, f"R{i - 1}", f"R{i}", f"{cs} * q{i} * deg")
        for r in range(1, 4):
            c(f"p{i}_{r} = p{i - 1}_{r} + R{i}_{r}1 * off[{i}, 1] + R{i}_{r}2 * off[{i}, 2] + R{i}_{r}3 * off[{i}, 3]")
    c.comment("error = target - current: position [m] and 0.5 rw sum c_i x t_i (the page's err)")
    for r in range(1, 4):
        c(f"e{r} = tp{r} - p7_{r}")
    hc = [[f"R7_{r}{i}" for r in range(1, 4)] for i in range(1, 4)]  # hand columns
    tc = [[f"T{i}_{r}" for r in range(1, 4)] for i in range(1, 4)]
    xs = [cross(hc[i], tc[i]) for i in range(3)]
    for r in range(3):
        c(f"e{r + 4} = 0.5 * rw * ({xs[0][r]} + {xs[1][r]} + {xs[2][r]})")
    c.comment("Jacobian d(current)/dq per degree (the exact derivative of -err), J5 column masked by the lock")
    for k in range(1, 8):
        u = [f"u{k}_{r}" for r in range(1, 4)]
        mask = " * act5" if k == 5 else ""
        lever = [f"(p7_{r} - o{k}_{r})" for r in range(1, 4)]
        pc = cross(u, lever)
        for r in range(3):
            c(f"J{r + 1}_{k} = deg * {pc[r]}{mask}")
        for i in range(3):
            uc = cross(u, hc[i])
            for r in range(3):
                c(f"g{k}{i + 1}_{r + 1} = {uc[r]}")
        terms = []
        for i in range(3):
            gi = [f"g{k}{i + 1}_{r}" for r in range(1, 4)]
            terms.append(cross(gi, tc[i]))
        for r in range(3):
            c(f"J{r + 4}_{k} = -0.5 * rw * deg * ({terms[0][r]} + {terms[1][r]} + {terms[2][r]}){mask}")
    c.comment("A = J J^T (6x6, symmetric)")
    for r in range(1, 7):
        for cc in range(r, 7):
            c(f"A{r}{cc} = " + " + ".join(f"J{r}_{k} * J{cc}_{k}" for k in range(1, 8)))
    c.comment("task step y = (A + lam I)^-1 e (Cholesky)")
    cholesky_solve(code, "A", "lam", [f"e{r}" for r in range(1, 7)], "y", "a")
    c.comment("null-space pull z toward home (the elbow bias moves the shoulder-yaw home, mirrored by s)")
    for k in range(1, 8):
        h = f"home[{k}]" + (" + s * obj[7]" if k == 3 else "")
        mask = "act5 * " if k == 5 else ""
        c(f"z{k} = {mask}kn * ({h} - q{k})")
    for r in range(1, 7):
        c(f"b{r} = " + " + ".join(f"J{r}_{k} * z{k}" for k in range(1, 8)))
    c.comment("its task-space part u = (A + lamn I)^-1 J z, removed so the pull acts in the null space")
    cholesky_solve(code, "A", "lamn", [f"b{r}" for r in range(1, 7)], "v", "b")
    c.comment("step d = z + J^T (y - u), scaled as a whole to at most dmax per joint and tick (a rate")
    c.comment("limit that keeps the step's direction, so a fast self-motion stays in the null space);")
    c.comment("the joints stay inside their limits")
    for k in range(1, 8):
        c(f"d{k} = z{k} + " + " + ".join(f"J{r}_{k} * (y{r} - v{r})" for r in range(1, 7)))
    c("dm = max(max(max(abs(d1), abs(d2)), max(abs(d3), abs(d4))), max(max(abs(d5), abs(d6)), abs(d7)))")
    c("sc = 1.0")
    c("if dm > dmax")
    c("    sc = dmax / dm")
    c("end")
    for k in range(1, 8):
        c(f"q{k} = clamp(q{k} + sc * d{k}, lo[{k}], hi[{k}])")
    c("q5 = act5 * q5")
    for k in range(1, 8):
        c(f"qr{k} = q{k} * deg")
    c.comment("readouts of the pose this tick started from (the page's: mm, deg, nearest limit in %)")
    c("pe = 1000.0 * sqrt(e1 * e1 + e2 * e2 + e3 * e3)")
    c("oe = asin(min(1.0, sqrt(e4 * e4 + e5 * e5 + e6 * e6) / rw)) / deg")
    c("m = 1.0")
    c("mj = 0.0")
    for k in range(1, 8):
        c(f"f{k} = min(q{k} - lo[{k}], hi[{k}] - q{k}) / (hi[{k}] - lo[{k}])")
        cond = f"f{k} < m" if k != 5 else "f5 < m && lockf < 0.5"
        c(f"if {cond}")
        c(f"    m = f{k}")
        c(f"    mj = {float(k)}")
        c("end")
    c("ex = o4_1")
    c("ey = o4_2")
    c("ez = o4_3")
    c("lim = 100.0 * m")
    c("limj = mj")
    c("held = 0.0")
    c("if pe < 2.0 && oe < 2.0")
    c("    held = 1.0")
    c("end")
    body = "\n".join(code.lines)
    params = [
        f'        s::Real = 1.0, [unit = "1", description = "Side: +1 the left arm (page +x), -1 the right arm (mirror)"]',
        f'        off::Mat{{7,3}} = {mat(srs.OFF_REAL)}, [unit = "m", description = "Offset after each joint, in its own frame (row k: joint k)"]',
        f'        lo::Vec{{7}} = {vec(srs.LO)}, [description = "Lower joint limits"]',
        f'        hi::Vec{{7}} = {vec(srs.HI)}, [description = "Upper joint limits"]',
        f'        home::Vec{{7}} = {vec(srs.HOME)}, [description = "Home posture of the null-space pull"]',
        f'        q0::Vec{{7}} = {vec(q0)}, [description = "Start posture (the IK warm start at the first tick)"]',
        f'        sx::Real = {num(srs.SHOULDER_X)}, [unit = "m", description = "Shoulder base at (s sx, sy0, 0)"]',
        f'        sy0::Real = {num(srs.SHOULDER_Y)}, [unit = "m", description = "Shoulder base height"]',
        f'        hb::Real = {num(srs.HB)}, [unit = "m", description = "Grasp point: half the object length"]',
        f'        rw::Real = {num(srs.RW)}, [unit = "m", min = 1.0e-6, description = "Orientation weight (m per rad)"]',
        f'        lam::Real = {num(srs.LAM_STEP)}, [min = 0, description = "Damping of the task step (per-degree Jacobian)"]',
        f'        lamn::Real = {num(srs.LAM_NULL)}, [min = 0, description = "Damping of the null-space projection"]',
        f'        kn::Real = {num(srs.K_NULL)}, [unit = "1", min = 0, description = "Null-space pull toward home per iteration"]',
        f'        dmax::Real = {num(0.05)}, [min = 0, description = "Largest joint step per tick in deg (the whole step is scaled down; 1 kHz: 50 deg/s)"]',
    ]
    outs = [f'        qr{k}::Real = {num(q0[k - 1] * srs.D)}, [unit = "rad", description = "Joint reference {k}"]' for k in range(1, 8)]
    outs += [
        '        pe::Real = 0.0, [description = "Hand position error of the solution"]',
        '        oe::Real = 0.0, [description = "Hand orientation error of the solution"]',
        '        lim::Real = 100.0, [description = "Nearest joint limit (0: at a limit)"]',
        '        limj::Real = 0.0, [unit = "1", description = "The joint of the nearest limit"]',
        '        held::Real = 1.0, [unit = "1", description = "1 when the pose is held (under 2 mm and 2 deg)"]',
        '        ex::Real = 0.0, [unit = "m", description = "Elbow (J4 origin) x, page frame"]',
        '        ey::Real = 0.0, [unit = "m", description = "Elbow y, page frame"]',
        '        ez::Real = 0.0, [unit = "m", description = "Elbow z, page frame"]',
    ]
    held = [f'        q{k}::Real = {num(q0[k - 1])}, [description = "Joint {k} of the solution"]' for k in range(1, 8)]
    held += ['        init::Real = 0.0, [unit = "1", description = "1 after the first tick"]']
    return (
        """@block ArmIK begin
    # 1 kHz inverse kinematics of one stacked 7-DOF SRS arm holding the shared object (sampled
    # firmware). Generated by design/build_library.py; its Python twin is
    # `srs.ik_step(..., jac="analytic")` (design/srs.py).
    #
    # The damped least squares of the interactive page, one iteration per tick, warm-started
    # from the last solution (the page runs 8 iterations per animation frame):
    #
    #   e  = target - current (position [m]; orientation 0.5 rw sum c_i x t_i)
    #   y  = (J J^T + lam I)^-1 e                      task step
    #   z  = kn (home - q)                             pull toward home (shoulder yaw + s bias)
    #   v  = (J J^T + lamn I)^-1 J z                   its task-space part
    #   d  = z + J^T (y - v), scaled down as a whole so that max |d_k| <= dmax (a rate limit)
    #   q += d, then clamp to the joint limits
    #
    # Angles in degrees, J per degree (the page's units, so lam, lamn and kn are the page's
    # constants); J is the exact derivative of the page's error, where the page takes a 1 deg
    # finite difference. With the lock (obj[8] = 1) J5 stays at zero: 6 joints for 6
    # constraints, no null space, so the elbow bias does nothing. Two Cholesky factorisations
    # of the 6x6 J J^T solve the systems.
    #
    # The chain (page frame): the shoulder base at (s sx, sy0, 0); joint k turns the frame by
    # -q (pitch joints) or s q (the others) about its axis (x z y x y x z), then the frame moves
    # by off[k, :]. s = -1 mirrors the arm. `off` = the stacked offsets, or zero shoulder and
    # wrist offsets for the ideal SRS.
    @parameters begin
"""
        + "\n".join(params)
        + """
    end
    @inputs obj::Vec{8}, [description = "Object (x, y, z [m], roll, pitch, yaw [deg]), elbow bias [deg], J5 lock"]
    @outputs begin
"""
        + "\n".join(outs)
        + """
    end
    @variables begin
"""
        + "\n".join(held)
        + """
    end
    @discrete Ts = 0.001 begin
"""
        + body
        + """
    end
end
"""
    )


# ===================================================================== ArmServo


def arm_servo(dz) -> str:
    lines = []
    for k in range(1, 8):
        lines += [
            f"        qdr{k} = (qr{k} - qp{k}) / Ts",
            f"        qp{k} = qr{k}",
            f"        e{k} = qr{k} - q{k}",
            f"        ei{k} = clamp(ei{k} + Ts * e{k}, -imax[{k}], imax[{k}])",
            f"        u{k} = clamp(tau0[{k}] + Kp[{k}] * e{k} + Ki[{k}] * ei{k} + Kd[{k}] * (qdr{k} - dq{k}), -umax[{k}], umax[{k}])",
            f"        err{k} = e{k}",
        ]
    ins = [f"        qr{k}::Real, [unit = \"rad\"]" for k in range(1, 8)]
    ins += [f"        q{k}::Real, [unit = \"rad\"]" for k in range(1, 8)]
    ins += [f"        dq{k}::Real, [unit = \"rad/s\"]" for k in range(1, 8)]
    outs = [f"        u{k}::Real = 0.0, [unit = \"N*m\"]" for k in range(1, 8)]
    outs += [f"        err{k}::Real = 0.0, [unit = \"rad\", description = \"Joint {k} tracking error\"]" for k in range(1, 8)]
    held = [f"        qp{k}::Real = 0.0, [unit = \"rad\", description = \"Joint {k} reference at the last tick\"]" for k in range(1, 8)]
    held += [f"        ei{k}::Real = 0.0, [unit = \"rad*s\", description = \"Joint {k} error integral\"]" for k in range(1, 8)]
    ex = dz.SERVO
    return (
        f"""@block ArmServo begin
    # 1 kHz joint servo of one arm (sampled firmware). Generated by design/build_library.py from
    # design/humanoid.py. Per joint k:
    #
    #   qdr = (qr - qr at the last tick) / Ts                   reference rate
    #   ei  = clamp(ei + Ts (qr - q), +-imax)                   error integral (anti-windup)
    #   u   = clamp(tau0 + Kp (qr - q) + Ki ei + Kd (qdr - dq), +-umax)
    #
    # tau0 is the static torque at the start posture (the drive springs start preloaded with it),
    # the integral takes up the gravity change along the task. Kp = B wn^2, Kd = 2 zeta B wn,
    # Ki = Kp wn / 5 with B the joint's inertia at the start posture plus the reflected rotor.
    # qp starts at the start posture `qp0`, so the first tick sees no reference step.
    @parameters begin
        Kp::Vec{{7}} = {vec(ex["Kp"])}, [unit = "N*m/rad", description = "Proportional gains"]
        Ki::Vec{{7}} = {vec(ex["Ki"])}, [unit = "N*m/(rad*s)", description = "Integral gains"]
        Kd::Vec{{7}} = {vec(ex["Kd"])}, [unit = "N*m*s/rad", description = "Rate gains"]
        umax::Vec{{7}} = {vec(ex["umax"])}, [unit = "N*m", description = "Torque limits"]
        imax::Vec{{7}} = {vec(ex["imax"])}, [unit = "rad*s", description = "Integral clamps"]
        tau0::Vec{{7}} = {vec(np.zeros(7))}, [unit = "N*m", description = "Static torque at the start posture"]
        qp0::Vec{{7}} = {vec(np.zeros(7))}, [unit = "rad", description = "Start posture (the first reference)"]
    end
    @inputs begin
"""
        + "\n".join(ins)
        + """
    end
    @outputs begin
"""
        + "\n".join(outs)
        + """
    end
    @variables begin
"""
        + "\n".join(held)
        + """
        init::Real = 0.0, [unit = "1", description = "1 after the first tick"]
    end
    @discrete Ts = """
        + num(dz.TS)
        + """ begin
        if init < 0.5
"""
        + "\n".join(f"            qp{k} = qp0[{k}]" for k in range(1, 8))
        + """
            init = 1.0
        end
"""
        + "\n".join(lines)
        + """
    end
end
"""
    )


