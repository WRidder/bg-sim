"""Writes ``scenes/segway.sdf``: the transporter with a rider on a tiled ground.

Z-up, metres. "body" has its frame at the centre of mass (x forward, y left); "wheel_l" and
"wheel_r" have their frame at the wheel centre with z along the axle (the rolling disc spins about
it), the frame the model's ``RollingDisk`` uses. All three follow the bound poses of the model:
``Pose/*`` for the body and ``PoseWL/g``, ``PoseWR/g`` for the wheels. The poses written here are the
start of the model ``balance`` (upright, at rest).

    uv run examples/segway/design/build_scene.py
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import design as d  # noqa: E402

D = d.D
ROOT = Path(__file__).resolve().parent.parent

L, R, B = D["l"], D["r"], D["b"]
PZ = R + L - 0.0008   # centre of mass at rest, about the static tyre penetration lower



def visual(out, name, geom, pose, rgba, indent="      "):
    x, y, z, roll, pitch, yaw = pose
    out.append(f'{indent}<visual name="{name}">')
    out.append(f'{indent}  <pose>{x:.4f} {y:.4f} {z:.4f} {roll:.5f} {pitch:.5f} {yaw:.5f}</pose>')
    out.append(f'{indent}  <geometry>{geom}</geometry>')
    out.append(f'{indent}  <material><diffuse>{rgba[0]} {rgba[1]} {rgba[2]} {rgba[3]}</diffuse></material>')
    out.append(f'{indent}</visual>')


def box(sx, sy, sz):
    return f"<box><size>{sx} {sy} {sz}</size></box>"


def cyl(rad, length):
    return f"<cylinder><radius>{rad}</radius><length>{length}</length></cylinder>"


def sphere(rad):
    return f"<sphere><radius>{rad}</radius></sphere>"




def write_scene(path, xr, yr, note):
    out: list[str] = []
    out.append('<?xml version="1.0"?>')
    out.append(f"""<!--
      segway: a two-wheeled self-balancing personal transporter with a rider. Generated by
      design/build_scene.py. Z-up, metres, the world frame of the model.

      "body" (frame at the body's centre of mass, {L} m above the axle; x forward, y left) follows
      Pose/q*, Pose/p*; "wheel_l" and "wheel_r" (frame at the wheel centre, z along the axle) follow
      PoseWL/g and PoseWR/g, so the wheels roll visibly: the dark spoke on each hub shows the rotation.
      The body link carries the platform, the two fenders, the battery box, the steering post with
      its handlebar and the rider (feet, legs, torso, arms, head). The ground is 2 m tiles, {note}.
    -->""")
    out.append('<sdf version="1.9">')
    out.append('  <model name="segway">')
    # ground tiles
    out.append('    <link name="ground">')
    out.append('      <pose>0 0 0 0 0 0</pose>')
    for i in range(xr[0], xr[1]):
        for j in range(yr[0], yr[1]):
            shade = (0.80, 0.82, 0.78, 1) if (i + j) % 2 == 0 else (0.72, 0.75, 0.70, 1)
            visual(out, f"tile_{i - xr[0]:02d}_{j - yr[0]:02d}", box(2, 2, 0.01), (2.0 * i + 1.0, 2.0 * j + 1.0, -0.008, 0, 0, 0), shade)
    out.append('    </link>')
    # body
    out.append('    <link name="body">')
    out.append(f'      <pose>0 0 {PZ:.4f} 0 0 0</pose>')
    BLUE = (0.18, 0.32, 0.62, 1)
    DARK = (0.16, 0.16, 0.18, 1)
    GREY = (0.62, 0.64, 0.68, 1)
    SKIN = (0.88, 0.70, 0.58, 1)
    SHIRT = (0.85, 0.35, 0.18, 1)
    JEANS = (0.22, 0.30, 0.50, 1)
    deck_z = -L - 0.04
    visual(out, "platform", box(0.36, 0.42, 0.04), (0.0, 0, deck_z, 0, 0, 0), DARK)
    visual(out, "battery_box", box(0.30, 0.34, 0.10), (0.0, 0, -L + 0.02, 0, 0, 0), BLUE)
    for tag, y in (("l", B / 2), ("r", -B / 2)):
        visual(out, f"fender_{tag}", box(0.56, 0.16, 0.025), (0.0, y, -L + R + 0.05, 0, 0, 0), BLUE)
        visual(out, f"fender_side_{tag}", box(0.40, 0.012, 0.15), (0.0, y + (0.075 if y > 0 else -0.075), -L + R - 0.02, 0, 0, 0), BLUE)
    visual(out, "post", cyl(0.028, 0.90), (0.14, 0, deck_z + 0.45, 0, 0.0, 0), GREY)
    visual(out, "handlebar", cyl(0.016, 0.50), (0.14, 0, deck_z + 0.90, 1.5707963, 0, 0), DARK)
    for tag, y in (("l", 0.11), ("r", -0.11)):
        visual(out, f"foot_{tag}", box(0.28, 0.10, 0.07), (0.0, y, deck_z + 0.055, 0, 0, 0), DARK)
        visual(out, f"leg_{tag}", cyl(0.070, 0.76), (-0.02, y, deck_z + 0.02 + 0.38, 0, 0.0, 0), JEANS)
        visual(out, f"arm_{tag}", cyl(0.040, 0.45), (0.06, 2 * y, 0.52, 0, 2.785, 0), SHIRT)
    visual(out, "torso", box(0.22, 0.36, 0.52), (-0.02, 0, 0.45, 0, 0, 0), SHIRT)
    visual(out, "head", sphere(0.11), (-0.02, 0, 0.90, 0, 0, 0), SKIN)
    out.append('    </link>')
    # wheels
    for tag, y in (("l", B / 2), ("r", -B / 2)):
        out.append(f'    <link name="wheel_{tag}">')
        out.append(f'      <pose>0 {y:.4f} {R - 0.0008:.4f} -1.5707963 0 0</pose>')
        visual(out, "tyre", cyl(R, 0.16), (0, 0, 0, 0, 0, 0), (0.10, 0.10, 0.11, 1))
        visual(out, "hub", cyl(0.17, 0.165), (0, 0, 0, 0, 0, 0), (0.70, 0.72, 0.75, 1))
        visual(out, "spoke", box(0.30, 0.05, 0.17), (0.0, 0, 0, 0, 0, 0), (0.85, 0.30, 0.12, 1))
        out.append('    </link>')
    out.append('  </model>')
    out.append('</sdf>')
    path.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print("wrote", path.relative_to(ROOT))



if __name__ == "__main__":
    sc = ROOT / "scenes"
    write_scene(sc / "segway.sdf", (-2, 10), (-2, 2), "x from -4 to 20 m, for the speed ramp and the push")
    write_scene(sc / "segway-close.sdf", (-1, 1), (-1, 1), "a 4 m square around the start")
    write_scene(sc / "segway-run.sdf", (-2, 32), (-2, 2), "x from -4 to 64 m, for the run to top speed")
    write_scene(sc / "segway-eight.sdf", (-4, 3), (-4, 4), "x from -8 to 6 m and y from -8 to 8 m, for the figure of eight")
