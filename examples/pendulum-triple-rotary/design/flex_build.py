"""Write the flexible-arm models of `pendulum-triple-rotary` from `design/design.json` and
`design/flex_design.json` (run `design.py`, `build_model.py` and `flex_design.py` first).

    uv run examples/pendulum-triple-rotary/design/flex_build.py

The rigid models, `library/RotaryCtrl.jl` and the rigid scene stay as `build_model.py` wrote them.
Each flexible model is the rigid bond graph (`triple_build.build_model`) with the arm's
`RigidBody3D` (and its transform, junction and pose blocks) replaced by a `FlexibleBeam3D` named
`Arm`: end A on the motor joint's child, end B on the first pendulum joint (through the transform
`L2/T`, now a pure rotation), `gA` from the joint chain, and the chain composed on from `Arm/poseB`.

    pendulum-triple-rotary-flex           the rigid firmware RotaryCtrl, unchanged (it fails)
    pendulum-triple-rotary-flex-lowpass   RotaryCtrlLP: the same weights, a 12 Hz low-pass in the loop
    pendulum-triple-rotary-flex-free      the controller off, released from the free-swing pose
"""

from __future__ import annotations

import json
import math
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import triple_build as tb  # noqa: E402

ROOT = HERE.parent
EXAMPLE = "pendulum-triple-rotary"
FLEX = f"{EXAMPLE}-flex"
LOWPASS = f"{EXAMPLE}-flex-lowpass"
FREE = f"{EXAMPLE}-flex-free"
SCENE = f"scenes/{FLEX}.sdf"
# the 3D view's deformation exaggeration a model opens with (scene.exaggeration): the arm bends by
# fractions of a millimetre while the pendulum is balanced and by about 1 mm in the swing-up
EXAGGERATION = {FLEX: 10, LOWPASS: 100, FREE: 100}

RJF_Q = tb.RJF[0]  # the first pendulum joint's frame in the arm frame, a pure rotation


def lp_controller_source(dz: dict, fz: dict) -> str:
    lp = fz["lp"]
    tab_x = np.array(dz["tab_x"])
    tab_u = np.array(dz["tab_u"])
    tab_k = np.array(lp["tab_k"])
    nx = tab_x.shape[1]
    nt = tab_x.shape[0]
    table = tb.mat(np.hstack([tab_x, tab_u[:, None], tab_k]))
    cols = 2 * nx + 3
    q = [f"q{i + 1}" for i in range(nx // 2)]
    w = [f"w{i + 1}" for i in range(nx // 2)]
    x = q + w
    af = lp["af"]
    bf = lp["bf"]
    lines = []
    add = lines.append
    add("@block RotaryCtrlLP begin")
    add("    # 1 kHz firmware of the rotary pendulum on the FLEXIBLE arm (generated by design/flex_build.py from")
    add("    # design.json and flex_design.json). RotaryCtrl with the feedback through a second-order low-pass:")
    add("    #")
    add("    #   phase 0  t < t_on            motor voltage 0 (hanging, at rest)")
    add("    #   phase 1  swing-up            w = -K(t) (x - x*(t)) - Kf(t) xf,   u = u*(t) + xf1")
    add("    #   phase 2  balance (latched)   w = -Klqr x - Kf xf,                u = xf1")
    add("    #   filter (every tick)           xf <- Af xf + Bf w")
    add("    #")
    add(f"    # The filter is 1/(s^2/wc^2 + 2 zeta s/wc + 1), wc = 2 pi {lp['fc']:g} Hz, zeta {lp['zeta']:g}, sampled with a")
    add("    # zero-order hold; xf = (y, y') is its state, y the feedback voltage. The gains K, Kf are the LQR and")
    add("    # the discrete TVLQR of the rigid sampled model WITH the filter in the loop (same weights as RotaryCtrl),")
    add("    # so the loop rolls off above about 12 Hz and leaves the arm mode (about 70 Hz) alone. The nominal")
    add("    # x*, u* is the rigid swing-up of RotaryCtrl, unchanged. A table row is [x*_1 .. x*_8, u*, K_1 .. K_8,")
    add("    # Kf_1, Kf_2]; the catch rule reads the x block of the LQR cost-to-go.")
    add(f"    @constants NT::Int = {nt}")
    add("    @inputs begin")
    for name in x:
        add(f"        {name}::Real")
    add("        tm::Real")
    add("    end")
    add("    @outputs begin")
    add('        u::Real = 0.0, [unit = "V"]')
    add("        phase::Real = 0.0")
    add("        vcost::Real = 0.0")
    add('        ufb::Real = 0.0, [unit = "V", description = "Filtered feedback voltage (xf1)"]')
    add("    end")
    add("    @parameters begin")
    add(f"        Tab::Mat{{NT,{cols}}} = {table}, [description = \"TVLQR table: x*, u*, K, Kf per row\"]")
    add(f"        Klqr::Vec{{{nx + 2}}} = {tb.vec(lp['k_lqr'])}, [description = \"LQR gain on x and the filter state\"]")
    add(f"        Pc::Mat{{{nx},{nx}}} = {tb.mat(lp['p_x'])}, [description = \"x block of the LQR cost-to-go (catch rule)\"]")
    add(f"        Af::Mat{{2,2}} = {tb.mat(af)}, [description = \"Low-pass filter, sampled: state matrix\"]")
    add(f"        Bf::Vec{{2}} = {tb.vec(bf)}, [description = \"Low-pass filter, sampled: input vector\"]")
    add('        t_on::Real = 1.0, [unit = "s", description = "Start of the swing-up"]')
    add('        t_s::Real = 4.0, [unit = "s", min = 0, description = "Swing-up duration of the trajectory"]')
    add('        dt_tab::Real = 0.01, [unit = "s", min = 0, description = "Row spacing of the table"]')
    add('        catch_tol::Real = 1.0, [min = 0, description = "Catch threshold of the cost-to-go x^T Pc x"]')
    add('        umax::Real = 15.0, [unit = "V", min = 0, description = "Amplifier voltage limit"]')
    add("    end")
    add("    @variables begin")
    add('        latched::Real = 0.0, [description = "1 once the balance controller has taken over"]')
    add('        xf1::Real = 0.0, [unit = "V", description = "Filter state: the filtered feedback voltage"]')
    add('        xf2::Real = 0.0, [unit = "V/s", description = "Filter state: its rate"]')
    add("    end")
    add("    @discrete Ts = 1e-3 begin")
    add("        tau = tm - t_on")
    add("        s = clamp(tau / dt_tab, 0.0, NT - 1.0) + 1.0")
    for c in range(cols):
        add(f"        c{c + 1} = 0.0")
    add("        for k in 1:NT")
    add("            wk = max(0.0, 1.0 - abs(s - k))")
    for c in range(cols):
        add(f"            c{c + 1} = c{c + 1} + wk * Tab[k, {c + 1}]")
    add("        end")
    terms_tv = " + ".join(f"c{nx + 2 + i} * ({x[i]} - c{i + 1})" for i in range(nx))
    terms_l = " + ".join(f"Klqr[{i + 1}] * {x[i]}" for i in range(nx))
    pc = np.array(lp["p_x"])
    norm = " + ".join(
        f"Pc[{i + 1}, {j + 1}] * {x[i]} * {x[j]}" if i == j else f"2.0 * Pc[{i + 1}, {j + 1}] * {x[i]} * {x[j]}"
        for i in range(nx)
        for j in range(i, nx)
        if abs(pc[i, j]) > 0.0 or i == j
    )
    add(f"        wtv = -({terms_tv}) - (c{2 * nx + 2} * xf1 + c{2 * nx + 3} * xf2)")
    add(f"        wlq = -({terms_l}) - (Klqr[{nx + 1}] * xf1 + Klqr[{nx + 2}] * xf2)")
    add(f"        en = {norm}")
    add("        lat = ifelse(latched > 0.5 || (tau >= t_s && en < catch_tol), 1.0, 0.0)")
    add("        latched = lat")
    add("        on = ifelse(tm < t_on, 0.0, 1.0)")
    add(f"        uff = ifelse(lat > 0.5, 0.0, c{nx + 1})")
    add("        wfb = on * ifelse(lat > 0.5, wlq, wtv)")
    add("        u = clamp(on * (uff + xf1), -umax, umax)")
    add("        ufb = xf1")
    add("        n1 = Af[1, 1] * xf1 + Af[1, 2] * xf2 + Bf[1] * wfb")
    add("        n2 = Af[2, 1] * xf1 + Af[2, 2] * xf2 + Bf[2] * wfb")
    add("        xf1 = n1")
    add("        xf2 = n2")
    add("        phase = ifelse(tm < t_on, 0.0, ifelse(lat > 0.5, 2.0, 1.0))")
    add("        vcost = en")
    add("    end")
    add("end")
    return "\n".join(lines) + "\n"


def _scene_has_exaggeration() -> bool:
    """The model contract's scene object offers a default exaggeration (contracts/schemas/model.schema.json)."""
    schema = json.loads((ROOT.parents[1] / "contracts" / "schemas" / "model.schema.json").read_text(encoding="utf-8"))
    return "exaggeration" in schema["$defs"]["scene"]["properties"]


def _drop(doc: dict, nodes: set[str]) -> None:
    dg = doc["diagram"]
    dg["nodes"] = [n for n in dg["nodes"] if n["id"] not in nodes]
    dg["connections"] = [c for c in dg["connections"] if c["from"]["node"] not in nodes and c["to"]["node"] not in nodes]


def _node(doc: dict, key: str) -> dict:
    return next(n for n in doc["diagram"]["nodes"] if n["id"] == key)


def _connect(doc: dict, kind: str, a, b) -> None:
    def end(pair):
        node, port = pair
        return {"node": node} if port is None else {"node": node, "port": port}

    conns = doc["diagram"]["connections"]
    conns.append({"id": f"{kind[0]}f{len(conns) + 1:03d}", "kind": kind, "from": end(a), "to": end(b), "route": [], "label": None})


def arm_params(fz: dict) -> tuple[dict, dict]:
    arm = fz["arm"]
    params = {
        "L": tb.fmt(arm["L"]), "E": tb.fmt(arm["E"]), "nu": tb.fmt(arm["nu"]), "rho": tb.fmt(arm["rho"]),
        "b": tb.fmt(arm["b"]), "h": tb.fmt(arm["h"]),
        "zeta_y": tb.fmt(arm["zeta"]), "zeta_z": tb.fmt(arm["zeta"]), "zeta_t": tb.fmt(arm["zeta"]),
        "g0": tb.fmt(9.81),
    }
    constants = {"ny": str(arm["ny"]), "nz": str(arm["nz"]), "nt": str(arm["nt"]), "basis": "0", "section": "2"}
    return params, constants


def flex_model(plant, dz: dict, fz: dict, name: str, kind: str) -> dict:
    """kind: "rigid-ctrl" (RotaryCtrl), "lowpass" (RotaryCtrlLP) or "free" (controller off)."""
    doc = tb.build_model(plant, dz, name, kind == "free")
    _drop(doc, {"link1", "bj1", "b1", "lc1", "pb1"})
    j1 = _node(doc, "j1")
    params, constants = arm_params(fz)
    doc["diagram"]["nodes"].append({
        "id": "arm", "name": "Arm", "block": {"ref": "stdlib:spatial/FlexibleBeam3D"},
        "position": {"x": j1["position"]["x"] + 290, "y": j1["position"]["y"] + 60}, "rotation": 0, "flipX": False,
        "params": params, "constants": constants, "starts": {}, "ui": {"showLabel": True, "color": None},
    })
    # the first pendulum joint sits on end B through a pure rotation (L2's T and LN); the chain
    # composes on Arm/poseB
    l2 = _node(doc, "l2")["params"]
    l2.update({f"T/{k}": v for k, v in tb.pose_params(tb.pose_inv(tb.RJF)).items()})
    l2.update({f"LN/{k}": v for k, v in tb.pose_params(tb.RJF).items()})
    dg = doc["diagram"]
    dg["connections"] = [c for c in dg["connections"]
                         if not (c["from"]["node"] == "w1" and c["to"]["node"] == "l2")]
    _connect(doc, "bond", ("j1", "child"), ("arm", "A"))
    _connect(doc, "bond", ("arm", "B"), ("l2", "parent"))
    _connect(doc, "signal", ("w1", "g"), ("arm", "gA"))
    _connect(doc, "signal", ("arm", "poseB"), ("l2", "gp"))
    if kind == "lowpass":
        ctrl = _node(doc, "ctrl")
        ctrl["block"] = {"ref": "project:RotaryCtrlLP"}
    n = plant.n_links
    doc["plots"] = [
        {"id": "p1", "title": "Link angles from upright", "signals": [f"Angles/phi{k}" for k in range(1, n + 1)]},
        {"id": "p2", "title": "Arm angle", "signals": ["J1/qout"]},
        {"id": "p3", "title": "Motor voltage", "signals": ["Ctrl/u"]},
        {"id": "p4", "title": "Arm tip deflection, horizontal and vertical (m)", "signals": ["Arm/dB[2]", "Arm/dB[3]"]},
        {"id": "p5", "title": "Modal coordinates of the arm (m)", "signals": ["Arm/eta_y[1]", "Arm/eta_y[2]", "Arm/eta_z[1]"]},
        {"id": "p6", "title": "Arm twist at the tip (rad)", "signals": ["Arm/twist"]},
        {"id": "p7", "title": "Controller phase", "signals": ["Ctrl/phase"]},
    ]
    if kind == "free":
        doc["plots"] = [p for p in doc["plots"] if p["id"] not in ("p3", "p7")]
        doc["plots"].append({"id": "p8", "title": "Arm energy: kinetic, strain, gravity (J)", "signals": ["Arm/Ek", "Arm/Ee", "Arm/Eg"]})
    doc["scene"] = {"file": SCENE}
    if _scene_has_exaggeration():
        doc["scene"]["exaggeration"] = EXAGGERATION[name]
    doc["bindings"] = flex_bindings(fz, n)
    doc["dashboard"] = dashboard(kind)
    doc["$comment"] = comment(dz, fz, kind)
    return doc


def flex_bindings(fz: dict, n: int) -> list[dict]:
    arm = fz["arm"]

    def pose(link: str, sig: str) -> dict:
        return {"target": f"link:{link}", "property": "pose", "signal": [f"{sig}[{i}]" for i in range(1, 8)]}

    out = [pose("arm_bar", "Arm/pose"), pose("arm_tip", "Arm/poseB")]
    out += [pose(f"rod{k}", f"L{k + 1}/W/g") for k in range(1, n + 1)]
    beam = {"axis": "+x", "y": "+y", "length": arm["L"]}
    for family, key, count in (("bending-y", "eta_y", arm["ny"]), ("bending-z", "eta_z", arm["nz"]), ("torsion", "eta_t", arm["nt"])):
        out.append({
            "target": "visual:arm_strip", "property": "deformation", "family": family, "basis": "clamped-free",
            "beam": dict(beam), "signal": [f"Arm/{key}[{i}]" for i in range(1, count + 1)],
        })
    return out


def dashboard(kind: str) -> dict:
    cards = [
        {"id": "angles", "kind": "plot", "size": "2x1", "title": "Link angles from upright", "signals": ["Angles/phi1", "Angles/phi2", "Angles/phi3"]},
        {"id": "tip", "kind": "plot", "size": "2x1", "title": "Arm tip deflection (m)", "signals": ["Arm/dB[2]", "Arm/dB[3]"]},
        {"id": "modes", "kind": "plot", "size": "2x1", "title": "Modal coordinates (m)", "signals": ["Arm/eta_y[1]", "Arm/eta_y[2]", "Arm/eta_z[1]"]},
    ]
    if kind != "free":
        cards.append({"id": "volt", "kind": "plot", "size": "2x1", "title": "Motor voltage (V)", "signals": ["Ctrl/u"]})
    cards += [
        {"id": "dev", "kind": "gauge", "size": "1x1", "title": "Largest link angle", "signals": ["Angles/dev"],
         "options": {"min": 0.0, "max": 0.2, "decimals": 3, "unit": "rad",
                     "zones": [{"from": 0.0, "to": 0.0175, "tone": "good"}, {"from": 0.0175, "to": 0.1, "tone": "warn"},
                               {"from": 0.1, "to": 0.2, "tone": "bad"}]}},
        {"id": "f1", "kind": "value", "size": "1x1", "title": "Bare arm, first mode", "signals": ["Arm/f_y[1]"],
         "options": {"decimals": 1, "unit": "Hz"}},
        {"id": "stiff", "kind": "number", "size": "1x1", "title": "Arm Young's modulus (Pa)", "parameter": "Arm/E",
         "options": {"min": 1.0e10, "max": 1.0e14, "decimals": 0, "unit": "Pa"}},
        {"id": "note", "kind": "text", "size": "1x1", "title": "Stiffness",
         "options": {"markdown": True, "text": "193e9 Pa is the stainless strip. The rigid gains need about 23x that (`pendulum-triple-rotary-flex`); the low-pass firmware holds from 0.5x up."}},
    ]
    return {"cards": cards, "autoRerun": False}


def comment(dz: dict, fz: dict, kind: str) -> str:
    arm = fz["arm"]
    base = (
        f"Flexible-arm variant of pendulum-triple-rotary: the arm is a FlexibleBeam3D (Arm), a {arm['b'] * 1e3:g} x "
        f"{arm['h'] * 1e3:g} mm stainless-steel strip on edge, {arm['L']:g} m, {arm['mass']:.3f} kg (the rigid arm's mass), "
        f"clamped-free modes ny = {arm['ny']}, nz = {arm['nz']}, nt = {arm['nt']}, zeta = {arm['zeta']:g}. End A on J1.child, "
        "end B on J2 through L2's T (a pure rotation), gA from W1, the chain composed on from Arm/poseB. "
    )
    tail = {
        "rigid-ctrl": "Ctrl is the rigid design's RotaryCtrl, unchanged: it excites the arm's first bending mode and never catches the pendulum.",
        "lowpass": "Ctrl is RotaryCtrlLP: the same weights, the LQR/TVLQR designed with a 12 Hz second-order low-pass in the feedback path; it catches and recovers.",
        "free": "The controller is off (t_on far in the future); the chain is released at rest from the free-swing pose of the rigid -free model.",
    }[kind]
    return base + tail


def scene_sdf(plant, fz: dict) -> str:
    arm = fz["arm"]
    la = arm["L"]
    colors = ["0.35 0.7 0.45 1", "0.85 0.35 0.3 1", "0.95 0.75 0.2 1"]
    out = [
        '<?xml version="1.0"?>',
        "<!--",
        f"  {FLEX}: the rotary triple pendulum on a flexible arm (a {arm['b'] * 1e3:g} x {arm['h'] * 1e3:g} mm steel strip on edge).",
        "",
        "  Z-up, metres. Every moving link is placed by a pose binding (no joints): the frames are the model's.",
        "    arm_bar  Arm/pose    the beam's reference frame = end A at the motor axis, x along the arm, z up",
        "    arm_tip  Arm/poseB   end B (deflected and turned with the tip slopes and the twist): the hinge housing",
        "    rodK     L{K+1}/W/g  the pendulum joint K's child frame: x along the link, z = the hinge axis",
        "  The strip `arm_strip` (a box from the hub, end A, to the tip, end B: beam axis +x, beam y +y, length",
        f"  {la:g} m) is deformed by Arm/eta_y[1..{arm['ny']}] (horizontal bending), Arm/eta_z[1..{arm['nz']}] (vertical) and",
        f"  Arm/eta_t[1..{arm['nt']}] (torsion), clamped-free basis. The scene is drawn at q = 0: the links upright.",
        "-->",
        '<sdf version="1.9">',
        f'  <model name="{FLEX.replace("-", "_")}">',
        '    <link name="base">',
        "      <pose>0 0 0 0 0 0</pose>",
        '      <visual name="servo_housing">',
        "        <pose>0 0 -0.06 0 0 0</pose>",
        "        <geometry><box><size>0.16 0.12 0.12</size></box></geometry>",
        "        <material><diffuse>0.2 0.2 0.22 1</diffuse></material>",
        "      </visual>",
        '      <visual name="base_plate">',
        "        <pose>0 0 -0.125 0 0 0</pose>",
        "        <geometry><box><size>0.34 0.24 0.01</size></box></geometry>",
        "        <material><diffuse>0.55 0.57 0.6 1</diffuse></material>",
        "      </visual>",
        "    </link>",
        '    <link name="arm_bar">',
        "      <pose>0 0 0 0 0 0</pose>",
        '      <visual name="hub">',
        "        <geometry><cylinder><radius>0.03</radius><length>0.03</length></cylinder></geometry>",
        "        <material><diffuse>0.25 0.5 0.85 1</diffuse></material>",
        "      </visual>",
        '      <visual name="arm_strip">',
        f"        <pose>{la / 2} 0 0 0 0 0</pose>",
        f"        <geometry><box><size>{la} {arm['b']} {arm['h']}</size></box></geometry>",
        "        <material><diffuse>0.72 0.74 0.78 1</diffuse></material>",
        "      </visual>",
        "    </link>",
        '    <link name="arm_tip">',
        f"      <pose>{la} 0 0 0 0 0</pose>",
        '      <visual name="tip_block">',
        "        <geometry><box><size>0.03 0.03 0.03</size></box></geometry>",
        "        <material><diffuse>0.2 0.2 0.22 1</diffuse></material>",
        "      </visual>",
        "    </link>",
    ]
    z0 = 0.0
    for k in range(plant.n_links):
        l = plant.lengths[k]
        # upright at q = 0: link x = world z, link z = world x (the hinge axis along the arm)
        out += [
            f'    <link name="rod{k + 1}">',
            f"      <pose>{la} 0 {z0} 3.1415927 -1.5707963 0</pose>",
            f'      <visual name="rod{k + 1}">',
            f"        <pose>{l / 2} 0 0 0 1.5707963 0</pose>",
            f"        <geometry><cylinder><radius>{0.006 - 0.001 * k}</radius><length>{l}</length></cylinder></geometry>",
            f"        <material><diffuse>{colors[k % 3]}</diffuse></material>",
            "      </visual>",
            f'      <visual name="joint{k + 1}">',
            "        <geometry><cylinder><radius>0.012</radius><length>0.03</length></cylinder></geometry>",
            "        <material><diffuse>0.2 0.2 0.22 1</diffuse></material>",
            "      </visual>",
        ]
        if k == plant.n_links - 1:
            out += [
                '      <visual name="tip">',
                f"        <pose>{l} 0 0 0 0 0</pose>",
                "        <geometry><sphere><radius>0.015</radius></sphere></geometry>",
                "        <material><diffuse>0.9 0.55 0.1 1</diffuse></material>",
                "      </visual>",
            ]
        out.append("    </link>")
        z0 += l
    out += ["  </model>", "</sdf>", ""]
    return "\n".join(out)


def main() -> None:
    dz = json.loads((HERE / "design.json").read_text(encoding="utf-8"))
    fz = json.loads((HERE / "flex_design.json").read_text(encoding="utf-8"))
    for key in ("tab_x", "tab_k"):
        dz[key] = np.array(dz[key])
    plant = tb.plant_from(dz)
    (ROOT / "library" / "RotaryCtrlLP.jl").write_text(lp_controller_source(json.loads((HERE / "design.json").read_text(encoding="utf-8")), fz),
                                                      encoding="utf-8", newline="\n")
    (ROOT / "scenes" / f"{FLEX}.sdf").write_text(scene_sdf(plant, fz), encoding="utf-8", newline="\n")
    for name, kind in ((FLEX, "rigid-ctrl"), (LOWPASS, "lowpass"), (FREE, "free")):
        tb.write_json(ROOT / "models" / f"{name}.bgmodel.json", flex_model(plant, dz, fz, name, kind))
    project = json.loads((ROOT / "bgsim.project.json").read_text(encoding="utf-8"))
    for name in (FLEX, LOWPASS, FREE):
        if name not in project["models"]:
            project["models"].append(name)
    tb.write_json(ROOT / "bgsim.project.json", project)
    print(f"wrote {FLEX}, {LOWPASS}, {FREE}, library/RotaryCtrlLP.jl and scenes/{FLEX}.sdf")


if __name__ == "__main__":
    main()
