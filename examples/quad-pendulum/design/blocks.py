"""Julia library blocks of `quad-pendulum`, generated from the design files (`design_<rig>.json`).

- `Quad<Rig>Ctrl`: the 1 kHz firmware (hold, TVLQR swing-up, latched LQR balance; saturation, slew-rate
  limit, optional actuator delay and encoder quantisation). The tables and gains are parameter defaults.
- `Quad<Rig>Monitor`: the measurements for the dashboard and the checks: absolute link angles (deg),
  energy per link from the bond graph's body twists and poses, the stacked energy, the energy ledger
  (work of the actuator, losses) and the upright reference level.
"""

from __future__ import annotations

import math

import numpy as np

N_DELAY = 10  # length of the actuator delay line (samples)


def fmt(v: float) -> str:
    return repr(float(v))


def vec(values) -> str:
    return "[" + ", ".join(f"{float(v):.12g}" for v in values) + "]"


def mat(rows) -> str:
    return "[" + "; ".join(" ".join(f"{float(v):.9g}" for v in row) for row in rows) + "]"


def ctrl_source(dz: dict) -> str:
    kind = dz["kind"]
    name = dz["ctrl_block"]
    n = len(dz["L"])
    nq = n + 1
    nx = 2 * nq
    unit_u = "N" if kind == "cart" else "N*m"
    unit_s = "m" if kind == "cart" else "rad"
    unit_sd = "m/s" if kind == "cart" else "rad/s"
    base = "cart position x" if kind == "cart" else "arm angle"
    act = "cart force F" if kind == "cart" else "arm torque"
    L = []
    A = L.append
    A(f"@block {name} begin")
    A(f"    # 1 kHz firmware of the quadruple pendulum on the {'cart' if kind == 'cart' else 'rotary arm'} (generated by")
    A("    # design/build_models.py from design/design_" + kind + ".json: do not edit the tables by hand).")
    A("    #")
    A(f"    #   phase 0  t < t_on            hold: {act} 0 (hanging at rest)")
    A("    #   phase 1  SWINGING UP         u = u*(tau) - K(tau) (z - z*(tau)), tau = t - t_on: the feed-forward and")
    A("    #                                time-varying LQR of the offline trajectory optimisation (looked up by")
    A(f"    #                                {dz['ctrl_block'].replace('Ctrl', 'Traj')} and sampled here: ff = u*, xs = z*, Ks = K)")
    A("    #   phase 2  BALANCING (latched) u = -Klqr z, the infinite-horizon discrete LQR at the upright")
    A("    #")
    A(f"    # z = [s, phi_1 .. phi_{n}, sd, phid_1 .. phid_{n}]: s the {base}, phi_i the absolute angle of link i from")
    A("    # the upward vertical (sums of the relative joint encoder angles). The catch latches phase 2 once, when")
    A("    # tau >= t_s - 0.5 s and the LQR cost-to-go z' Pc z is below catch_tol (the catch region).")
    A("    # balance_only starts in phase 2 (the balance scenario).")
    A("    #")
    A("    # Actuator: the command is clamped to +-u_max, then slew-rate limited (slew per second) and finally")
    A(f"    # delayed by delay_n whole samples (0 .. {N_DELAY}). Sensors: with `quant` the encoders are quantised")
    A("    # (res_s, res_q) and the rates are filtered backward differences (time constant tau_f) instead of the")
    A("    # exact rates. The zero-order hold breaks the algebraic loop through the plant.")
    A("    @inputs begin")
    A('        tm::Real, [unit = "s"]')
    A(f'        s::Real, [unit = "{unit_s}"]')
    A(f'        sd::Real, [unit = "{unit_sd}"]')
    for i in range(n):
        A(f'        q{i + 1}::Real, [unit = "rad"]')
    for i in range(n):
        A(f'        wq{i + 1}::Real, [unit = "rad/s"]')
    A(f'        ff::Real, [unit = "{unit_u}"]')
    A(f"        xs::Vec{{{nx}}}")
    A(f"        Ks::Vec{{{nx}}}")
    A("    end")
    A("    @outputs begin")
    A(f'        u::Real = 0.0, [unit = "{unit_u}", description = "Applied {act}"]')
    A(f'        ucmd::Real = 0.0, [unit = "{unit_u}", description = "Controller command before the slew limit and the delay"]')
    A('        phase::Real = 0.0, [description = "0 hold, 1 swinging up (TVLQR), 2 balancing (LQR)"]')
    A('        swinging::Real = 0.0, [description = "1 while swinging up"]')
    A('        balancing::Real = 0.0, [description = "1 while balancing"]')
    A('        vcost::Real = 0.0, [description = "LQR cost-to-go of the measured state (catch region test)"]')
    A("    end")
    A("    @parameters begin")
    A(f'        Klqr::Vec{{{nx}}} = {vec(dz["k_lqr"])}, [description = "Balance LQR gain (u = -Klqr z)"]')
    A(f'        Pc::Mat{{{nx},{nx}}} = {mat(dz["p_lqr"])}, [description = "LQR cost-to-go matrix of the catch region"]')
    A(f'        t_on::Real = {fmt(dz["t_on"])}, [unit = "s", description = "Start of the swing-up"]')
    A(f'        t_s::Real = {fmt(dz["t_s"])}, [unit = "s", min = 0, description = "Duration of the swing-up trajectory"]')
    A(f'        catch_tol::Real = {fmt(dz["catch_tol"])}, [min = 0, description = "Catch region: z\' Pc z below this"]')
    A(f'        u_max::Real = {fmt(dz["u_max"])}, [unit = "{unit_u}", min = 0, description = "Actuator limit"]')
    A(f'        slew::Real = {fmt(dz["slew"])}, [unit = "{unit_u}/s", min = 0, description = "Actuator slew-rate limit"]')
    A('        delay_n::Real = 0.0, [min = 0, max = ' + str(N_DELAY) + ', description = "Actuator delay in samples of 1 ms"]')
    A('        quant::Bool = false, [description = "Quantised encoders and difference rates"]')
    A(f'        res_s::Real = {fmt(dz["res_s"])}, [unit = "{unit_s}", min = 0, description = "Base encoder resolution"]')
    A(f'        res_q::Real = {fmt(dz["res_q"])}, [unit = "rad", min = 0, description = "Joint encoder resolution"]')
    A(f'        tau_f::Real = {fmt(dz["tau_f"])}, [unit = "s", min = 0, description = "Rate filter time constant (quantised mode)"]')
    A('        balance_only::Bool = false, [description = "Start in the balance phase (no swing-up)"]')
    A("    end")
    A("    @variables begin")
    A('        latched::Real = 0.0, [description = "1 once the balance controller has taken over"]')
    A('        ulast::Real = 0.0, [description = "Last slew-limited output"]')
    A('        started::Real = 0.0, [description = "1 after the first tick"]')
    for k in range(N_DELAY):
        A(f'        d{k + 1}::Real = 0.0')
    for k in range(nq):
        A(f'        pp{k + 1}::Real = 0.0')
        A(f'        wf{k + 1}::Real = 0.0')
    A("    end")
    A("    @discrete Ts = 1e-3 begin")
    # measured joint positions (base, relative joint angles)
    if kind == "cart":
        A("        r1 = q1 - 1.5707963267948966")
    else:
        A("        r1 = q1")
    for i in range(1, n):
        A(f"        r{i + 1} = q{i + 1}")
    A("        m0 = s")
    for i in range(n):
        A(f"        m{i + 1} = r{i + 1}")
    A("        if quant")
    A("            m0 = res_s * round(s / res_s)")
    for i in range(n):
        A(f"            m{i + 1} = res_q * round(r{i + 1} / res_q)")
    A("        end")
    # absolute angles
    A("        p1 = m1")
    for i in range(1, n):
        A(f"        p{i + 1} = p{i} + m{i + 1}")
    # rates
    A("        v0 = sd")
    A("        v1 = wq1")
    for i in range(1, n):
        A(f"        v{i + 1} = v{i} + wq{i + 1}")
    A("        af = 0.001 / (0.001 + tau_f)")
    pos = ["m0"] + [f"p{i + 1}" for i in range(n)]
    for k in range(nq):
        A(f"        wf{k + 1} = ifelse(started > 0.5, wf{k + 1} + af * (({pos[k]} - pp{k + 1}) / 0.001 - wf{k + 1}), 0.0)")
        A(f"        pp{k + 1} = {pos[k]}")
    A("        started = 1.0")
    A("        if quant")
    A("            v0 = wf1")
    for i in range(n):
        A(f"            v{i + 1} = wf{i + 2}")
    A("        end")
    z = ["m0"] + [f"p{i + 1}" for i in range(n)] + ["v0"] + [f"v{i + 1}" for i in range(n)]
    A("        tau = tm - t_on")
    terms_tv = " + ".join(f"Ks[{i + 1}] * ({z[i]} - xs[{i + 1}])" for i in range(nx))
    terms_l = " + ".join(f"Klqr[{i + 1}] * {z[i]}" for i in range(nx))
    A(f"        utv = ff - ({terms_tv})")
    A(f"        ulq = -({terms_l})")
    norm = " + ".join(
        f"Pc[{i + 1}, {i + 1}] * {z[i]} * {z[i]}" if i == j else f"2.0 * Pc[{i + 1}, {j + 1}] * {z[i]} * {z[j]}"
        for i in range(nx) for j in range(i, nx))
    A(f"        en = {norm}")
    A("        lat = ifelse(balance_only, 1.0, ifelse(latched > 0.5 || (tm >= t_on && tau >= t_s - 0.5 && en < catch_tol), 1.0, 0.0))")
    A("        latched = lat")
    A("        cmd = clamp(ifelse(lat > 0.5, ulq, ifelse(tm < t_on, 0.0, utv)), -u_max, u_max)")
    A("        du = slew * 0.001")
    A("        out = clamp(cmd, ulast - du, ulast + du)")
    A("        ulast = out")
    for k in range(N_DELAY - 1, 0, -1):
        A(f"        d{k + 1} = d{k}")
    A("        d1 = out")
    sel = " + ".join(f"ifelse(abs(delay_n - {k + 1}.0) < 0.5, d{k + 2}, 0.0)" for k in range(N_DELAY - 1))
    A(f"        u = ifelse(delay_n < 0.5, out, {sel})")
    A("        ucmd = cmd")
    A("        phase = ifelse(lat > 0.5, 2.0, ifelse(tm < t_on, 0.0, 1.0))")
    A("        swinging = ifelse(phase > 0.5 && phase < 1.5, 1.0, 0.0)")
    A("        balancing = ifelse(phase > 1.5, 1.0, 0.0)")
    A("        vcost = en")
    A("    end")
    A("end")
    return "\n".join(L) + "\n"


def traj_source(dz: dict) -> str:
    """The swing-up tables (feed-forward, nominal state, TVLQR gains) as a continuous lookup (interp1)."""
    name = dz["ctrl_block"].replace("Ctrl", "Traj")
    n = len(dz["L"])
    nx = 2 * (n + 1)
    unit_u = "N" if dz["kind"] == "cart" else "N*m"
    tab_x, tab_u, tab_k = np.array(dz["tab_x"]), np.array(dz["tab_u"]), np.array(dz["tab_k"])
    nt = len(tab_u)
    tk = np.arange(nt) * dz["dt_tab"]
    names = ["s"] + [f"phi{i + 1}" for i in range(n)] + ["sd"] + [f"phid{i + 1}" for i in range(n)]
    L = []
    A = L.append
    A(f"@block {name} begin")
    A(f"    # Swing-up tables of the quadruple pendulum (design/design.py, {dz['dt_tab'] * 1000:g} ms knots): the feed-forward")
    A("    # u*, the nominal state z* = [s, phi_1.., sd, phid_1..] and the TVLQR gain row K (u = u* - K (z - z*)),")
    A("    # looked up linearly at tau = t - t_on and held at the ends (the last row is upright at rest with the")
    A("    # balance LQR gain). interp1 is an equation-scope intrinsic, so the lookup is continuous; the firmware")
    A("    # samples these outputs at its ticks. Generated by design/build_models.py: do not edit by hand.")
    A(f"    @constants NK::Int = {nt}")
    A('    @inputs tm::Real, [unit = "s"]')
    A("    @outputs begin")
    A(f'        ff::Real, [unit = "{unit_u}", description = "Feed-forward"]')
    A(f"        xs::Vec{{{nx}}}")
    A(f"        Ks::Vec{{{nx}}}")
    A("    end")
    A("    @parameters begin")
    A(f'        t_on::Real = {fmt(dz["t_on"])}, [unit = "s", description = "Start of the swing-up"]')
    A(f'        tk::Vec{{NK}} = {vec(tk)}, [unit = "s", description = "Knots"]')
    A(f'        uff::Vec{{NK}} = {vec(tab_u)}, [unit = "{unit_u}", description = "Feed-forward"]')
    for i in range(nx):
        A(f'        z{i + 1}::Vec{{NK}} = {vec(tab_x[:, i])}, [description = "Nominal {names[i]}"]')
    for i in range(nx):
        A(f'        k{i + 1}::Vec{{NK}} = {vec(tab_k[:, i])}, [description = "TVLQR gain on {names[i]}"]')
    A("    end")
    A("    @equations begin")
    A("        ff ~ interp1(tm - t_on, tk, uff)")
    for i in range(nx):
        A(f"        xs[{i + 1}] ~ interp1(tm - t_on, tk, z{i + 1})")
    for i in range(nx):
        A(f"        Ks[{i + 1}] ~ interp1(tm - t_on, tk, k{i + 1})")
    A("    end")
    A("end")
    return "\n".join(L) + "\n"


def monitor_source(dz: dict) -> str:
    """Angles, energy per link, stacked energy, ledger. Body twists V and poses g come from the bond graph."""
    kind = dz["kind"]
    name = dz["monitor_block"]
    n = len(dz["L"])
    nv, ng = (3, 3) if kind == "cart" else (6, 7)
    unit_u = "N" if kind == "cart" else "N*m"
    L = []
    A = L.append
    A(f"@block {name} begin")
    A("    # Measurements of the quadruple pendulum (generated by design/build_models.py).")
    A("    #")
    A("    # Angles: phi_i, the absolute angle of link i from the upward vertical (deg), from the relative joint")
    A("    # angles; dev the largest |phi_i|.")
    if kind == "cart":
        A("    # Energy per link i from the bond graph's body i (RigidBody2D at the link's centre of mass): its twist")
        A("    # V = [w, vx, vy] (body frame) and its pose g = [theta, x, y]:")
        A("    #   E_i = J_i w^2/2 + m_i (vx^2 + vy^2)/2 + m_i g0 (y - y_hang_i),")
    else:
        A("    # Energy per link i from the bond graph's body i (RigidBody3D at the link's centre of mass): its twist")
        A("    # V = [w; v] (body frame, principal axes) and its pose g = [quaternion; position]:")
        A("    #   E_i = sum_k Jp_ik w_k^2/2 + m_i |v|^2/2 + m_i g0 (z - z_hang_i),")
    A("    # potential measured from the hanging rest, so the hanging chain has E = 0 and the upright chain at rest")
    A("    # E_up = sum m_i g0 2 (L_1 + .. + L_{i-1} + c_i). S_k = E_1 + .. + E_k is the stacked energy.")
    A("    # Ledger: E_tot = E_base + sum E_i, W_in = int u * sd dt (work of the actuator), W_loss = int (b_s sd^2 +")
    A("    # sum b_j wq_j^2) dt (base and joint friction); E_tot - W_in + W_loss stays constant up to the energy in")
    A("    # the stiff pivots.")
    A("    @inputs begin")
    A('        sd::Real, [unit = "' + ("m/s" if kind == "cart" else "rad/s") + '"]')
    A(f'        u::Real, [unit = "{unit_u}"]')
    for i in range(n):
        A(f'        q{i + 1}::Real, [unit = "rad"]')
    for i in range(n):
        A(f'        wq{i + 1}::Real, [unit = "rad/s"]')
    for i in range(n):
        A(f"        V{i + 1}::Vec{{{nv}}}")
    for i in range(n):
        A(f"        g{i + 1}::Vec{{{ng}}}")
    A("    end")
    A("    @outputs begin")
    for i in range(n):
        A(f'        th{i + 1}::Real, [description = "Link {i + 1} from the upward vertical (deg)"]')
    A('        dev::Real, [description = "Largest |angle| of the links from upright (deg)"]')
    for i in range(n):
        A(f'        E{i + 1}::Real, [unit = "J", description = "Energy of link {i + 1} (kinetic + potential from hanging)"]')
    for i in range(n):
        A(f'        S{i + 1}::Real, [unit = "J", description = "Stacked energy E_1 + .. + E_{i + 1}"]')
    A('        E_up::Real, [unit = "J", description = "UPRIGHT level: the chain upright at rest"]')
    A('        E_base::Real, [unit = "J", description = "Kinetic energy of the ' + ("cart" if kind == "cart" else "arm and hub") + '"]')
    A('        E_tot::Real, [unit = "J", description = "Total mechanical energy"]')
    A('        W_in::Real, [unit = "J", description = "Work done by the actuator"]')
    A('        W_loss::Real, [unit = "J", description = "Energy dissipated by friction"]')
    A('        ledger::Real, [unit = "J", description = "E_tot - W_in + W_loss (constant)"]')
    A("    end")
    A("    @parameters begin")
    A(f'        m::Vec{{{n}}} = {vec(dz["m_model"])}, [unit = "kg", description = "Link masses"]')
    if kind == "cart":
        A(f'        J::Vec{{{n}}} = {vec(dz["J_model"])}, [unit = "kg*m^2", description = "Link inertias about the COM"]')
    else:
        for i in range(n):
            A(f'        Jp{i + 1}::Vec{{3}} = {vec(dz["Jp_model"][i])}, [unit = "kg*m^2", description = "Principal inertias of link {i + 1}"]')
    A(f'        h_hang::Vec{{{n}}} = {vec(dz["h_hang"])}, [unit = "m", description = "Height of each COM at the hanging rest"]')
    if kind == "cart":
        A(f'        m_base::Real = {fmt(dz["m_base"])}, [unit = "kg", description = "Cart mass"]')
    else:
        A(f'        J_axis::Real = {fmt(dz["J_axis"])}, [unit = "kg*m^2", description = "Arm and hub inertia about the vertical axis"]')
    A(f'        b_s::Real = {fmt(dz["b_base"])}, [description = "Base friction coefficient"]')
    A(f'        b_j::Real = {fmt(dz["b_joint"])}, [unit = "N*m*s/rad", description = "Joint friction coefficient"]')
    A(f'        g0::Real = {fmt(9.81)}, [unit = "m/s^2"]')
    A("    end")
    A("    @variables begin")
    A('        Win::Real = 0.0, [unit = "J"]')
    A('        Wloss::Real = 0.0, [unit = "J"]')
    A("    end")
    A("    @equations begin")
    if kind == "cart":
        A("        th1 ~ (q1 - 1.5707963267948966) * 57.29577951308232")
    else:
        A("        th1 ~ q1 * 57.29577951308232")
    for i in range(1, n):
        A(f"        th{i + 1} ~ th{i} + q{i + 1} * 57.29577951308232")
    A("        dev ~ max(max(abs(th1), abs(th2)), max(abs(th3), abs(th4)))")
    for i in range(n):
        k = i + 1
        if kind == "cart":
            A(f"        E{k} ~ 0.5 * J[{k}] * V{k}[1]^2 + 0.5 * m[{k}] * (V{k}[2]^2 + V{k}[3]^2) + m[{k}] * g0 * (g{k}[3] - h_hang[{k}])")
        else:
            A(f"        E{k} ~ 0.5 * (Jp{k}[1] * V{k}[1]^2 + Jp{k}[2] * V{k}[2]^2 + Jp{k}[3] * V{k}[3]^2) + "
              f"0.5 * m[{k}] * (V{k}[4]^2 + V{k}[5]^2 + V{k}[6]^2) + m[{k}] * g0 * (g{k}[7] - h_hang[{k}])")
    A("        S1 ~ E1")
    for i in range(1, n):
        A(f"        S{i + 1} ~ S{i} + E{i + 1}")
    A("        E_up ~ " + " + ".join(f"m[{i + 1}] * g0 * (-2.0 * h_hang[{i + 1}])" for i in range(n)))
    if kind == "cart":
        A("        E_base ~ 0.5 * m_base * sd^2")
    else:
        A("        E_base ~ 0.5 * J_axis * sd^2")
    A(f"        E_tot ~ E_base + S{n}")
    A("        ddt(Win) ~ u * sd")
    A("        ddt(Wloss) ~ b_s * sd^2 + b_j * (" + " + ".join(f"wq{i + 1}^2" for i in range(n)) + ")")
    A("        W_in ~ Win")
    A("        W_loss ~ Wloss")
    A("        ledger ~ E_tot - Win + Wloss")
    A("    end")
    A("end")
    return "\n".join(L) + "\n"
