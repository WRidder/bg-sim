"""3D scenes of `quad-pendulum` (SDF): the cart on its rail and the rotary arm, each with four links
coloured from deep blue to white and a ball at every joint (the look of the reference video)."""

from __future__ import annotations

# deep blue -> white, one per link
COLORS = ["0.10 0.30 0.85 1", "0.30 0.52 0.95 1", "0.60 0.76 1.0 1", "0.93 0.95 1.0 1"]
BALL = "0.95 0.75 0.25 1"
# the short-travel controller's limit: a thin translucent green line, not a stop
LIMIT = "0.2 0.85 0.45 0.55"


def _visual(name, pose, geom, color, indent="      "):
    return [f'{indent}<visual name="{name}">', f"{indent}  <pose>{pose}</pose>",
            f"{indent}  <geometry>{geom}</geometry>", f"{indent}  <material><diffuse>{color}</diffuse></material>",
            f"{indent}</visual>"]


def cart_sdf(dz: dict, limit: float | None = None) -> str:
    L = dz["L"]
    n = len(L)
    rail = dz["s_max"]
    out = [
        '<?xml version="1.0"?>',
        "<!--",
        "  quad-pendulum: a cart on a rail carrying a chain of four pendulum links, in the vertical X-Z plane.",
        "",
        "  The model is planar in its x-y plane with gravity along -y; the scene uses the SDF X-Z plane (model x",
        "  = SDF X, model y = SDF Z) and the model's counter-clockwise angles are rotations about -Y. The origin is",
        "  the cart pivot. Joint \"rail\" (prismatic, +X) follows Rail/qout; \"hinge1\" the angle of link 1 from the",
        "  world +X axis (Joint1/qout: -pi/2 hanging, +pi/2 upright); \"hinge2\" .. \"hinge4\" the relative angles",
        f"  Joint2..4/qout. At q = 0 the links lie along +X; each is {L[0]:g} m. The rail is +-{rail:g} m between the",
        "  red end stops, with a marker every 0.5 m (the centre one white). The thin green lines at +-limit mark the",
        "  travel limit of the short-travel controller: visual only (the plant has no stop there). Generated by",
        "  design/build_models.py.",
        "-->",
        '<sdf version="1.9">',
        '  <model name="quad_pendulum">',
        '    <link name="rail_base">',
        "      <pose>0 0 0 0 0 0</pose>",
    ]
    out += _visual("rail_beam", "0 0 -0.11 0 0 0", f"<box><size>{2 * rail + 0.3:.3f} 0.08 0.03</size></box>", "0.22 0.24 0.28 1")
    out += _visual("rail_top", "0 0 -0.09 0 1.5707963 0", f"<cylinder><radius>0.01</radius><length>{2 * rail + 0.2:.3f}</length></cylinder>",
                   "0.65 0.67 0.7 1")
    for side, x in (("left", -rail - 0.1), ("right", rail + 0.1)):
        out += _visual(f"stop_{side}", f"{x:.3f} 0 -0.07 0 0 0", "<box><size>0.04 0.1 0.1</size></box>", "0.85 0.22 0.2 1")
    k = 0
    xm = -int(rail / 0.5) * 0.5
    while xm <= rail + 1e-9:
        col = "0.95 0.95 0.95 1" if abs(xm) < 1e-9 else "0.95 0.75 0.25 1"
        h = 0.05 if abs(xm) < 1e-9 else 0.03
        out += _visual(f"marker{k}", f"{xm:.3f} 0.045 -0.11 0 0 0", f"<box><size>0.012 0.012 {h}</size></box>", col)
        k += 1
        xm += 0.5
    if limit is not None:
        for side, x in (("lo", -limit), ("hi", limit)):
            out += _visual(f"limit_{side}", f"{x:.3f} 0 0.05 0 0 0", "<box><size>0.004 0.004 0.33</size></box>", LIMIT)
            out += _visual(f"limit_{side}_floor", f"{x:.3f} 0 -0.125 0 0 0", "<box><size>0.006 0.5 0.003</size></box>", LIMIT)
    out += _visual("floor", "0 0 -0.13 0 0 0", f"<box><size>{2 * rail + 0.6:.3f} 0.6 0.005</size></box>", "0.12 0.13 0.15 1")
    out += ["    </link>", '    <link name="cart">', "      <pose>0 0 0 0 0 0</pose>"]
    out += _visual("cart_body", "0 0 -0.035 0 0 0", "<box><size>0.18 0.1 0.06</size></box>", "0.18 0.2 0.24 1")
    out += _visual("cart_top", "0 0 -0.004 0 0 0", "<box><size>0.16 0.08 0.006</size></box>", "0.1 0.3 0.85 1")
    for i, (wx, wy) in enumerate(((-0.06, 0.055), (0.06, 0.055), (-0.06, -0.055), (0.06, -0.055))):
        out += _visual(f"wheel{i + 1}", f"{wx} {wy} -0.075 1.5707963 0 0", "<cylinder><radius>0.022</radius><length>0.014</length></cylinder>",
                       "0.08 0.08 0.09 1")
    out += _visual("pivot_post", "0 0 0 1.5707963 0 0", "<cylinder><radius>0.012</radius><length>0.06</length></cylinder>", "0.6 0.62 0.66 1")
    out.append("    </link>")
    x0 = 0.0
    for i in range(n):
        out += [f'    <link name="link{i + 1}">', f"      <pose>{x0:.4f} 0 0 0 0 0</pose>"]
        out += _visual(f"link{i + 1}_bar", f"{L[i] / 2:.4f} 0 0 0 1.5707963 0",
                       f"<cylinder><radius>{0.012 - 0.0015 * i:.4f}</radius><length>{L[i]:.4f}</length></cylinder>", COLORS[i])
        out += _visual(f"joint{i + 1}_ball", "0 0 0 0 0 0", f"<sphere><radius>{0.022 - 0.002 * i:.4f}</radius></sphere>", BALL)
        if i == n - 1:
            out += _visual("tip_ball", f"{L[i]:.4f} 0 0 0 0 0", "<sphere><radius>0.016</radius></sphere>", "0.95 0.95 0.95 1")
        out.append("    </link>")
        x0 += L[i]
    out += ['    <joint name="rail" type="prismatic">', "      <parent>rail_base</parent>", "      <child>cart</child>",
            "      <axis><xyz>1 0 0</xyz></axis>", "    </joint>"]
    for i in range(n):
        parent = "cart" if i == 0 else f"link{i}"
        out += [f'    <joint name="hinge{i + 1}" type="revolute">', f"      <parent>{parent}</parent>",
                f"      <child>link{i + 1}</child>", "      <axis><xyz>0 -1 0</xyz></axis>", "    </joint>"]
    out += ["  </model>", "</sdf>", ""]
    return "\n".join(out)


def rotary_sdf(dz: dict, limit: float | None = None) -> str:
    L = dz["L"]
    n = len(L)
    la = dz["arm_l"]
    out = [
        '<?xml version="1.0"?>',
        "<!--",
        "  quad-pendulum (rotary): a horizontal arm turning about the vertical axis carries a chain of four",
        "  pendulum links at its tip (a Furuta pendulum with four links).",
        "",
        "  Z-up, metres, drawn at q = 0: the arm along +X, the links standing upright (+Z) on its tip. Joint",
        "  \"arm\" turns about +Z (L1/J/qout); joints \"link1\" .. \"link4\" turn about the arm axis +X (L2..L5/J/qout,",
        *(["  relative to the link below; the hanging start is L2/J/q = pi). The two thin green lines on the base plate at",
           "  +-limit from the arm's zero mark the travel limit of the short-travel controller: visual only (the arm joint",
           "  has no stop). Generated by design/build_models.py."] if limit is not None else
          ["  relative to the link below; the hanging start is L2/J/q = pi). Generated by design/build_models.py."]),
        "-->",
        '<sdf version="1.9">',
        '  <model name="quad_pendulum_rotary">',
        '    <link name="base">',
        "      <pose>0 0 0 0 0 0</pose>",
    ]
    out += _visual("column", "0 0 -0.38 0 0 0", "<cylinder><radius>0.04</radius><length>0.72</length></cylinder>", "0.18 0.2 0.24 1")
    out += _visual("base_plate", "0 0 -0.746 0 0 0", "<box><size>0.9 0.9 0.012</size></box>", "0.3 0.32 0.36 1")
    for k in range(12):
        import math
        a = 2 * math.pi * k / 12
        col = "0.95 0.95 0.95 1" if k == 0 else "0.95 0.75 0.25 1"
        out += _visual(f"marker{k}", f"{0.40 * math.cos(a):.4f} {0.40 * math.sin(a):.4f} -0.737 0 0 {a:.4f}",
                       "<box><size>0.03 0.008 0.004</size></box>", col)
    if limit is not None:
        import math
        for side, a in (("lo", -limit), ("hi", limit)):
            r0, r1 = 0.08, 0.44
            rm = (r0 + r1) / 2
            out += _visual(f"limit_{side}", f"{rm * math.cos(a):.4f} {rm * math.sin(a):.4f} -0.737 0 0 {a:.4f}",
                           f"<box><size>{r1 - r0:.3f} 0.005 0.003</size></box>", LIMIT)
    out += ["    </link>", '    <link name="arm_bar">', "      <pose>0 0 0 0 0 0</pose>"]
    out += _visual("hub", "0 0 0 0 0 0", "<cylinder><radius>0.035</radius><length>0.04</length></cylinder>", "0.1 0.3 0.85 1")
    out += _visual("arm", f"{la / 2:.4f} 0 0 0 1.5707963 0", f"<cylinder><radius>0.01</radius><length>{la:.4f}</length></cylinder>",
                   "0.1 0.3 0.85 1")
    out += _visual("tip_block", f"{la:.4f} 0 0 0 0 0", "<box><size>0.035 0.035 0.035</size></box>", "0.18 0.2 0.24 1")
    out.append("    </link>")
    z0 = 0.0
    for i in range(n):
        out += [f'    <link name="rod{i + 1}">', f"      <pose>{la:.4f} 0 {z0:.4f} 0 0 0</pose>"]
        out += _visual(f"rod{i + 1}_bar", f"0 0 {L[i] / 2:.4f} 0 0 0",
                       f"<cylinder><radius>{0.007 - 0.001 * i:.4f}</radius><length>{L[i]:.4f}</length></cylinder>", COLORS[i])
        out += _visual(f"joint{i + 1}_ball", "0 0 0 0 0 0", f"<sphere><radius>{0.014 - 0.0015 * i:.4f}</radius></sphere>", BALL)
        if i == n - 1:
            out += _visual("tip_ball", f"0 0 {L[i]:.4f} 0 0 0", "<sphere><radius>0.011</radius></sphere>", "0.95 0.95 0.95 1")
        out.append("    </link>")
        z0 += L[i]
    out += ['    <joint name="arm" type="revolute">', "      <parent>base</parent>", "      <child>arm_bar</child>",
            "      <axis><xyz>0 0 1</xyz></axis>", "    </joint>"]
    for i in range(n):
        parent = "arm_bar" if i == 0 else f"rod{i}"
        out += [f'    <joint name="link{i + 1}" type="revolute">', f"      <parent>{parent}</parent>",
                f"      <child>rod{i + 1}</child>", "      <axis><xyz>1 0 0</xyz></axis>", "    </joint>"]
    out += ["  </model>", "</sdf>", ""]
    return "\n".join(out)
