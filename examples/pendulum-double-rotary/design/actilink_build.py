"""Write the ACTILINK models of pendulum-double-rotary (`actilink-*`), the generated controller
block `library/ALCtrl.jl`, the scene `scenes/actilink.sdf` and the project's model list, from
`design/actilink_design.json` (run `actilink_design.py` first).

    uv run examples/pendulum-double-rotary/design/actilink_build.py

Bond graph of every model (multibond for the rig, one-dimensional bonds for the drive)::

    Uq (MSe) -> One_e -> R (R_eq), I (L_eq), Isense (Df), GY (p lambda) -> One_m
    One_m -> Rotor (I, J_m), FricIn (ALFriction), Wm (Df), Gear (TF, 1/N) -> Zero_g
    Zero_g -> GearSpring (ALGearSpring: compliance, backlash, contact damping) and Zero_g -> One_o
    One_o -> FricOut (ALFriction, output bearing) and One_o -> J1.drive (Revolute3D, the arm)
    J2.drive, J3.drive (the passive joints) -> 1-junctions with ALFriction (and ALClamp in the
    identification fixtures)

Firmware: current loop <- ALDriveLoop (4 kHz, CST/CSV) <- ALCtrl (1 kHz, balance and swing-up) or
ALSysidCmd (1 kHz, the excitation of an identification experiment). The current loop is the digital
16 kHz ALCurrentLoop in the current-step experiment and its continuous equivalent ALCurrentLoopC
(same PI, clamp, anti-windup, 1.5-period delay as a lag) everywhere else: a 16 kHz held output
records 32 000 event rows per second. Sensors: the drive's motor and output encoders (stdlib
Encoder, 19/20 bit, read at the 1 kHz cycle; the motor encoder at 4 kHz in CSV) and two AS5048
chains (SPI and I2C latency) on each passive joint.
"""

from __future__ import annotations

import math
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import actilink_lib as al
import rotary_build as rb

ROOT = HERE.parent
fmt, vec, mat, pose_params = rb.fmt, rb.vec, rb.mat, rb.pose_params
IDENTITY = rb.IDENTITY
K_JOINT = 1.0e6


# ------------------------------------------------------------------ the controller block
def ctrl_source(dz: dict) -> str:
    tab = np.array(dz["tab"])
    nt, cols = tab.shape
    lines: list[str] = []
    add = lines.append
    add("@block ALCtrl begin")
    add("    # 1 kHz outer controller of the ACTILINK rotary double pendulum (EtherCAT master, CST mode).")
    add("    # Generated by design/actilink_build.py from design/actilink_design.json.")
    add("    #")
    add("    # Measurement: q0m the arm angle from the drive's 20-bit output encoder; m1*, m2* the AS5048")
    add("    # registers of the two passive joints for the SPI chain (a) and the I2C chain (b), `bus` picks")
    add("    # the chain. Each register minus its calibration offset (z: the reading at the hanging rest,")
    add("    # minus pi for link 1) is unwrapped against the last angle (wrap to +-pi of the increment).")
    add("    # Estimator: per joint an alpha-beta-gamma filter, the steady-state Kalman filter of a white-")
    add("    # jerk kinematic model (gains G[j, :] = angle, rate, acceleration), predict then correct.")
    add("    #")
    add("    #   mode 0  t < t_on                  torque 0")
    add("    #   mode 1  swing-up                  tau = tau*(t) - K(t) (x - x*(t)), the TVLQR table Tab")
    add("    #                                     (rows every dt_tab: x*, tau*, K), linear interpolation")
    add("    #   mode 2  balance (latched)         tau = -K x - K7 tau_prev, the discrete LQR designed with")
    add("    #                                     the one-cycle EtherCAT delay as a state")
    add("    #")
    add("    # The switch to mode 2 happens once: at t_on with balance_only = 1, else when t - t_on >= t_s")
    add("    # and the weighted norm sqrt(sum cw x^2) is below catch_tol. tau is clamped to +-umax, and with")
    add("    # n_delay = 1 the command computed in a cycle is sent in the next one.")
    add(f"    @constants NT::Int = {nt}")
    add("    @inputs begin")
    add('        q0m::Real, [unit = "rad", description = "Arm angle (output encoder)"]')
    for name, what in (("m1a", "link 1, AS5048A (SPI)"), ("m2a", "link 2, AS5048A (SPI)"),
                       ("m1b", "link 1, AS5048B (I2C)"), ("m2b", "link 2, AS5048B (I2C)")):
        add(f'        {name}::Real, [unit = "rad", description = "Register, {what}"]')
    add('        tm::Real, [unit = "s"]')
    add("    end")
    add("    @outputs begin")
    add('        tau::Real = 0.0, [unit = "N*m", description = "Target torque sent to the drive"]')
    add('        mode::Real = 0.0, [description = "0 idle, 1 swing-up, 2 balance"]')
    for j in range(3):
        add(f'        q{j + 1}e::Real = 0.0, [unit = "rad", description = "Estimated joint {j + 1} angle"]')
    for j in range(3):
        add(f'        w{j + 1}e::Real = 0.0, [unit = "rad/s", description = "Estimated joint {j + 1} rate"]')
    add('        th1::Real = 0.0, [unit = "rad", description = "Measured link 1 angle (unwrapped)"]')
    add('        th2::Real = 0.0, [unit = "rad", description = "Measured link 2 angle (unwrapped)"]')
    add('        enorm::Real = 0.0, [description = "Catch norm"]')
    add("    end")
    add("    @parameters begin")
    add(f'        Tab::Mat{{NT,{cols}}} = {mat(tab)}, [description = "TVLQR table: x*, tau*, K per row"]')
    add(f'        K::Vec{{7}} = {vec(dz["K"])}, [description = "Balance LQR gain on [x, tau_prev]"]')
    add(f'        G::Mat{{3,3}} = {mat(dz["abg"])}, [description = "Estimator gains per joint (angle, rate, acceleration)"]')
    add(f'        cw::Vec{{6}} = {vec(dz["catch_w"])}, [description = "Weights of the catch norm"]')
    add(f'        t_on::Real = {fmt(dz["t_on"])}, [unit = "s", description = "Controller start"]')
    add(f'        t_s::Real = {fmt(dz["t_s"])}, [unit = "s", min = 0, description = "Swing-up duration"]')
    add(f'        dt_tab::Real = {fmt(dz["dt_tab"])}, [unit = "s", min = 0, description = "Row spacing of the table"]')
    add(f'        catch_tol::Real = {fmt(dz["catch_tol"])}, [min = 0, description = "Catch threshold"]')
    add(f'        umax::Real = {fmt(dz["umax"])}, [unit = "N*m", min = 0, description = "Torque command limit"]')
    add('        balance_only::Real = 0.0, [description = "1: balance from t_on (no swing-up)"]')
    add('        bus::Bool = false, [description = "Encoder chain: false AS5048A (SPI), true AS5048B (I2C)"]')
    add('        n_delay::Real = 1.0, [description = "EtherCAT cycles between computation and drive (0 or 1)"]')
    add('        th1_init::Real = 3.141592653589793, [unit = "rad", description = "Expected link 1 angle at the first cycle"]')
    for name in ("z1a", "z2a", "z1b", "z2b"):
        add(f'        {name}::Real = {fmt(dz["zcal"][name])}, [unit = "rad", description = "Calibration offset of encoder {name[1]}{name[2]}"]')
    add("    end")
    add("    @variables begin")
    add('        init::Real = 0.0, [description = "1 after the first cycle"]')
    add('        latched::Real = 0.0, [description = "1 once the balance controller has taken over"]')
    add('        up::Real = 0.0, [unit = "N*m", description = "Command of the last cycle"]')
    add('        u1::Real = 0.0, [unit = "rad", description = "Unwrapped link 1 angle"]')
    add('        u2::Real = 0.0, [unit = "rad", description = "Unwrapped link 2 angle"]')
    for j in range(1, 4):
        add(f'        a{j}::Real = 0.0, [description = "Joint {j}: estimated angle"]')
        add(f'        v{j}::Real = 0.0, [description = "Joint {j}: estimated rate"]')
        add(f'        c{j}::Real = 0.0, [description = "Joint {j}: estimated acceleration"]')
    add("    end")
    add("    @discrete Ts = 1e-3 begin")
    add("        m1 = ifelse(bus, m1b - z1b, m1a - z1a)")
    add("        m2 = ifelse(bus, m2b - z2b, m2a - z2a)")
    add("        if init < 0.5")
    add("            d1 = m1 - th1_init")
    add("            u1 = th1_init + d1 - 6.283185307179586 * floor((d1 + 3.141592653589793) / 6.283185307179586)")
    add("            u2 = m2 - 6.283185307179586 * floor((m2 + 3.141592653589793) / 6.283185307179586)")
    add("            a1 = q0m")
    add("            a2 = u1")
    add("            a3 = u2")
    add("            init = 1.0")
    add("        end")
    add("        d1 = m1 - u1")
    add("        u1 = u1 + d1 - 6.283185307179586 * floor((d1 + 3.141592653589793) / 6.283185307179586)")
    add("        d2 = m2 - u2")
    add("        u2 = u2 + d2 - 6.283185307179586 * floor((d2 + 3.141592653589793) / 6.283185307179586)")
    for j, meas in ((1, "q0m"), (2, "u1"), (3, "u2")):
        add(f"        ap = a{j} + Ts * v{j} + 0.5 * Ts * Ts * c{j}")
        add(f"        vp = v{j} + Ts * c{j}")
        add(f"        r = {meas} - ap")
        add(f"        a{j} = ap + G[{j}, 1] * r")
        add(f"        v{j} = vp + G[{j}, 2] * r")
        add(f"        c{j} = c{j} + G[{j}, 3] * r")
    x = ["a1", "a2", "a3", "v1", "v2", "v3"]
    add("        tau_on = tm - t_on")
    add("        s = clamp(tau_on / dt_tab, 0.0, NT - 1.0) + 1.0")
    for c in range(cols):
        add(f"        t{c + 1} = 0.0")
    add("        for k in 1:NT")
    add("            wk = max(0.0, 1.0 - abs(s - k))")
    for c in range(cols):
        add(f"            t{c + 1} = t{c + 1} + wk * Tab[k, {c + 1}]")
    add("        end")
    tv = " + ".join(f"t{8 + i} * ({x[i]} - t{i + 1})" for i in range(6))
    lq = " + ".join(f"K[{i + 1}] * {x[i]}" for i in range(6))
    norm = " + ".join(f"cw[{i + 1}] * {x[i]} * {x[i]}" for i in range(6))
    add(f"        utv = t7 - ({tv})")
    add(f"        ulq = -({lq} + K[7] * up)")
    add(f"        en = sqrt({norm})")
    add("        if tm >= t_on && (balance_only > 0.5 || (tau_on >= t_s && en < catch_tol))")
    add("            latched = 1.0")
    add("        end")
    add("        u = ifelse(tm < t_on, 0.0, ifelse(latched > 0.5, ulq, utv))")
    add("        u = clamp(u, -umax, umax)")
    add("        tau = ifelse(n_delay > 0.5, up, u)")
    add("        up = u")
    add("        mode = ifelse(tm < t_on, 0.0, ifelse(latched > 0.5, 2.0, 1.0))")
    for j in range(3):
        add(f"        q{j + 1}e = a{j + 1}")
        add(f"        w{j + 1}e = v{j + 1}")
    add("        th1 = u1")
    add("        th2 = u2")
    add("        enorm = en")
    add("    end")
    add("end")
    return "\n".join(lines) + "\n"


# ------------------------------------------------------------------ geometry
def geometry(rg: dict):
    b = rg["bodies"]
    ln = [IDENTITY, (rb.RJF[0], (rg["arm_l"], 0.0, 0.0)), (IDENTITY[0], (rg["link_l"], 0.0, rg["offset2"]))]
    lc = [(IDENTITY[0], (bb.c, 0.0, 0.0)) for bb in b]
    return ln, lc, [bb.m for bb in b], [bb.J for bb in b]


# ------------------------------------------------------------------ the model builder
def build(dz: dict, spec: dict) -> dict:
    """One model document. spec: name, comment, t_end, q0 (start angles), firmware ('ctrl' |
    'sysid' | 'none'), ctrl / sysid / drive parameter overrides, clamps {1|2|3: k}, push, plots,
    dashboard, solver settings."""
    dr = al.drive(dz["size"])
    rg = al.rig()
    ln, lc, mass, inertia = geometry(rg)
    q0 = list(spec["q0"])
    deflections = rb.static_deflections(ln, lc, mass, q0, K_JOINT)
    distal = [sum(mass[j:]) for j in range(3)]
    reach = rg["arm_l"] + 2 * rg["link_l"]
    jref = [sum(m * reach**2 + max(jj) for m, jj in zip(mass[j:], inertia[j:], strict=True)) for j in range(3)]
    d = rb.Diagram()
    names = ["Arm", "Link1", "Link2"]
    bx = [380, 840, 1300]
    ry = [320, 540, 760]
    band = 1100
    d.ref("world", "World", "stdlib:multibond/GroundSpatial", bx[0] - 140, ry[0])
    d.ref("mount", "Mount", "stdlib:multibond/FixedTransform3DNeutral", bx[0], ry[0], params=pose_params(IDENTITY))
    d.ref("mpose", "MountPose", "stdlib:spatial/LocalPose3D", bx[0] - 140, band, params=pose_params(IDENTITY))
    d.connect("bond", ("world", "p"), ("mount", "b"))
    prev_world = "mpose"
    for i in range(3):
        k = i + 1
        x0, y0 = bx[i], ry[i]
        d.ref(
            f"j{k}", f"J{k}", "stdlib:spatial/Revolute3D", x0 + 120, y0,
            params={"kt": fmt(K_JOINT), "kr": fmt(K_JOINT), "bt": fmt(1.4 * math.sqrt(K_JOINT * distal[i])),
                    "br": fmt(1.4 * math.sqrt(K_JOINT * jref[i])), "q0": fmt(q0[i])},
            starts={"dth": vec(deflections[i][0]), "dl": vec(deflections[i][1])},
        )  # fmt: skip
        d.ref(f"link{k}", f"COM{k}", "stdlib:multibond/FixedTransform3DNeutral", x0 + 240, y0, params=pose_params(lc[i]))
        d.junction(f"bj{k}", f"BJ{k}", x0 + 360, y0 + 10)
        d.ref(f"b{k}", names[i], "stdlib:spatial/RigidBody3D", x0 + 350, y0 + 100,
              params={"m": fmt(mass[i]), "J": vec(inertia[i]), "g0": fmt(al.G)})
        if i == 0:
            d.connect("bond", ("mount", "a"), ("j1", "parent"))
        else:
            t_pose = rb.pose_mul(rb.pose_inv(ln[i]), lc[i - 1])
            d.ref(f"t{k}", f"T{k}", "stdlib:multibond/FixedTransform3DNeutral", x0, y0, params=pose_params(t_pose))
            d.connect("bond", (f"t{k}", "a"), (f"j{k}", "parent"))
            d.connect("bond", (f"t{k}", "b"), (f"bj{k - 1}", None))
        d.connect("bond", (f"j{k}", "child"), (f"link{k}", "a"))
        d.connect("bond", (f"link{k}", "b"), (f"bj{k}", None))
        d.connect("bond", (f"b{k}", "p"), (f"bj{k}", None))
        d.ref(f"ln{k}", f"LN{k}", "stdlib:spatial/LocalPose3D", x0, band + 100, params=pose_params(ln[i]))
        d.ref(f"ca{k}", f"CA{k}", "stdlib:multibond/ComposePose3D", x0, band)
        d.ref(f"w{k}", f"W{k}", "stdlib:multibond/ComposePose3D", x0 + 120, band)
        d.ref(f"lc{k}", f"LC{k}", "stdlib:spatial/LocalPose3D", x0 + 350, band + 240, params=pose_params(lc[i]))
        d.ref(f"pb{k}", f"P{k}", "stdlib:multibond/ComposePose3D", x0 + 350, band + 120)
        d.connect("signal", (prev_world, "g"), (f"ca{k}", "gp"))
        d.connect("signal", (f"ln{k}", "g"), (f"ca{k}", "gl"))
        d.connect("signal", (f"ca{k}", "g"), (f"w{k}", "gp"))
        d.connect("signal", (f"j{k}", "pose"), (f"w{k}", "gl"))
        d.connect("signal", (f"w{k}", "g"), (f"pb{k}", "gp"))
        d.connect("signal", (f"lc{k}", "g"), (f"pb{k}", "gl"))
        d.connect("signal", (f"pb{k}", "g"), (f"b{k}", "g"))
        prev_world = f"w{k}"

    clamps = spec.get("clamps", {})
    # passive joints: bearing friction (+ the clamp of an identification fixture)
    for i in (1, 2):
        k = i + 1
        x0, y0 = bx[i] + 120, ry[i] - 150
        d.junction(f"jj{k}", f"JJ{k}", x0, y0)
        d.ref(f"fj{k}", f"FricJ{k}", "project:ALFriction", x0 + 120, y0 - 40,
              params={"Fc": fmt(rg["Fc_j"]), "Fs": fmt(rg["Fc_j"]), "vs": "1.0", "Fv": fmt(rg["Fv_j"]), "v_eps": fmt(al.V_EPS_J)})
        d.connect("bond", (f"jj{k}", None), (f"j{k}", "drive"))
        d.connect("bond", (f"jj{k}", None), (f"fj{k}", "p"))
        if k in clamps:
            d.ref(f"cl{k}", f"Clamp{k}", "project:ALClamp", x0 + 120, y0 + 40, params={"k": fmt(clamps[k]), "d": fmt(spec.get("clamp_d", 5.0))})
            d.connect("bond", (f"jj{k}", None), (f"cl{k}", "p"))

    # ------------------------------------------------ the drive (bond graph)
    yd = 1700
    xd = 60
    d.ref("uq", "Uq", "stdlib:bondgraph/MSe", xd, yd, params={"gain": "1.0"})
    d.junction("e1", "One_e", xd + 130, yd)
    d.ref("rw", "Rw", "stdlib:bondgraph/R", xd + 130, yd + 120, params={"r": fmt(dr.R_eq)})
    d.ref("lw", "Lw", "stdlib:bondgraph/I", xd + 230, yd + 120, params={"i": fmt(dr.L_eq)})
    d.ref("isense", "Isense", "stdlib:bondgraph/Df", xd + 130, yd - 120)
    d.ref("gy", "EMF", "stdlib:bondgraph/GY", xd + 270, yd, params={"r": fmt(dr.r_gy)})
    d.junction("m1", "One_m", xd + 410, yd)
    d.ref("rotor", "Rotor", "stdlib:bondgraph/I", xd + 410, yd + 120, params={"i": fmt(dr.J_m)})
    d.ref("fin", "FricIn", "project:ALFriction", xd + 520, yd + 120,
          params={"Fc": fmt(dr.Fc_in / dr.N), "Fs": fmt(dr.Fs_in / dr.N), "vs": fmt(dr.vs_in * dr.N),
                  "Fv": fmt(dr.Fv_in / dr.N**2), "v_eps": fmt(al.V_EPS_OUT * dr.N)})  # fmt: skip
    d.ref("wm", "Wm", "stdlib:bondgraph/Df", xd + 410, yd - 120)
    d.ref("gear", "Gear", "stdlib:bondgraph/TF", xd + 560, yd, params={"n": fmt(1.0 / dr.N)})
    d.node("g0", "Zero_g", {"junction": "0"}, xd + 700, yd)
    d.ref("spring", "GearSpring", "project:ALGearSpring", xd + 700, yd + 120,
          params={"k1": fmt(dr.k1), "k3": fmt(dr.k3), "tau_knee": fmt(dr.tau_knee),
                  "backlash": fmt(spec.get("backlash", dr.backlash)), "d": fmt(dr.gear_damping)})  # fmt: skip
    d.junction("o1", "One_o", xd + 840, yd)
    d.ref("fout", "FricOut", "project:ALFriction", xd + 840, yd + 120,
          params={"Fc": fmt(dr.Fc_out), "Fs": fmt(dr.Fc_out), "vs": "1.0", "Fv": fmt(dr.Fv_out), "v_eps": fmt(al.V_EPS_OUT)})
    d.connect("bond", ("uq", "p"), ("e1", None))
    d.connect("bond", ("e1", None), ("rw", "p"))
    d.connect("bond", ("e1", None), ("lw", "p"))
    d.connect("bond", ("e1", None), ("isense", "p"))
    d.connect("bond", ("e1", None), ("gy", "p1"))
    d.connect("bond", ("gy", "p2"), ("m1", None))
    d.connect("bond", ("m1", None), ("rotor", "p"))
    d.connect("bond", ("m1", None), ("fin", "p"))
    d.connect("bond", ("m1", None), ("wm", "p"))
    d.connect("bond", ("m1", None), ("gear", "p1"))
    d.connect("bond", ("gear", "p2"), ("g0", None))
    d.connect("bond", ("g0", None), ("spring", "p"))
    d.connect("bond", ("g0", None), ("o1", None))
    d.connect("bond", ("o1", None), ("fout", "p"))
    d.connect("bond", ("o1", None), ("j1", "drive"))
    if 1 in clamps:
        d.ref("cl1", "Clamp1", "project:ALClamp", xd + 960, yd + 120, params={"k": fmt(clamps[1]), "d": fmt(spec.get("clamp_d1", 200.0))})
        d.connect("bond", ("o1", None), ("cl1", "p"))

    # sensors of the drive: motor angle (integral of the rotor speed) and the two encoders
    d.ref("thm", "MotorAngle", "stdlib:continuous/Integrator", xd + 560, yd - 240)
    d.connect("signal", ("wm", "y"), ("thm", "u"))
    d.ref("menc", "MotorEnc", "stdlib:motion/Encoder", xd + 700, yd - 240,
          params={"cpr": str(2**dr.motor_bits)}, constants={"sample_period": "0.00025" if spec.get("drive_mode") else "0.001"})
    d.connect("signal", ("thm", "y"), ("menc", "u"))
    d.ref("oenc", "OutputEnc", "stdlib:motion/Encoder", bx[0] + 120, ry[0] - 200,
          params={"cpr": str(2**dr.out_bits)}, constants={"sample_period": "0.001"})
    d.connect("signal", ("j1", "qout"), ("oenc", "u"))

    # drive firmware (spec "drive_off": the power stage disabled with the motor terminals shorted, u_q = 0, no
    # loops; for the experiments with a clamped arm, where the drive plays no part)
    fw = dz["fw"]
    drive_off = bool(spec.get("drive_off"))
    if drive_off:
        d.ref("uoff", "UqOff", "stdlib:sources/Constant", xd, yd - 240, params={"value": "0.0"})
        d.connect("signal", ("uoff", "y"), ("uq", "u"))
    else:
        digital = spec.get("current_loop") == "digital"
        d.ref("cur", "CurrentLoop", "project:ALCurrentLoop" if digital else "project:ALCurrentLoopC", xd, yd - 240,
              params={"kp": fmt(fw["kp_i"]), "ki": fmt(fw["ki_i"]), "umax": fmt(dr.uq_max)})
        d.connect("signal", ("cur", "uq"), ("uq", "u"))
        d.connect("signal", ("isense", "y"), ("cur", "ie"))
        dparams = {"mode": fmt(spec.get("drive_mode", 0.0)), "N": fmt(dr.N), "kt_q": fmt(dr.kt_q), "iq_max": fmt(dr.iq_peak),
                   "kp_w": fmt(fw["kp_w"]), "ki_w": fmt(fw["ki_w"])}
        d.ref("drv", "DriveLoop", "project:ALDriveLoop", xd + 200, yd - 360, params=dparams)
        d.connect("signal", ("drv", "iref"), ("cur", "iref"))
        d.connect("signal", ("menc", "y"), ("drv", "thm"))
    d.ref("clock", "Clock", "stdlib:sources/Time", xd - 160, 60)

    # AS5048 chains: SPI (A) and I2C (B) on both passive joints, each with its own seeded noise
    enc = dz["enc"]
    for k, (jn, col) in enumerate((("j2", 1), ("j3", 2))):
        for chain, lat, base in (("A", enc["lat_a"], 0), ("B", enc["lat_b"], 2)):
            node = f"enc{col}{chain.lower()}"
            p = enc[f"inl{col}"]
            d.ref(node, f"Enc{col}{chain}", "project:AS5048", 1500 + 160 * (base + col), 120,
                  params={"lat": fmt(lat), "a1": fmt(p[0]), "p1": fmt(p[1]), "a2": fmt(p[2]), "p2": fmt(p[3]),
                          "sigma": fmt(enc["sigma"]), "zero": fmt(enc[f"zero{col}"]), "nrd": "enc_nrd"},
                  constants={"sample_period": "0.001"})  # fmt: skip
            d.ref(f"nz{col}{chain.lower()}", f"Noise{col}{chain}", "stdlib:sources/Noise", 1500 + 160 * (base + col), 0,
                  params={"seed": str(10 + col + base), "std": "1.0"}, constants={"sample_time": "0.001"})
            d.connect("signal", (f"nz{col}{chain.lower()}", "y"), (node, "z"))
            d.connect("signal", (jn, "qout"), (node, "theta"))
            d.connect("signal", (jn, "qdout"), (node, "w"))

    firmware = spec["firmware"]
    if firmware == "ctrl":
        cp = {"t_on": fmt(spec.get("t_on", dz["t_on"])), "balance_only": fmt(spec.get("balance_only", 0.0)),
              "th1_init": fmt(spec.get("th1_init", math.pi)), "bus": "true" if spec.get("bus") else "false"}
        d.ref("ctrl", "Ctrl", "project:ALCtrl", 1300, 60, params=cp, constants={"NT": str(len(dz["tab"]))})
        d.connect("signal", ("clock", "y"), ("ctrl", "tm"))
        d.connect("signal", ("oenc", "y"), ("ctrl", "q0m"))
        for col in (1, 2):
            for chain in ("a", "b"):
                d.connect("signal", (f"enc{col}{chain}", "y"), ("ctrl", f"m{col}{chain}"))
        d.connect("signal", ("ctrl", "tau"), ("drv", "tau_cmd"))
        d.ref("wzero", "WZero", "stdlib:sources/Constant", xd + 40, yd - 480, params={"value": "0.0"})
        d.connect("signal", ("wzero", "y"), ("drv", "w_cmd"))
    elif firmware == "sysid":
        sp = {k: (vec(v) if isinstance(v, list) else fmt(v)) for k, v in spec["sysid"].items()}
        d.ref("cmd", "Cmd", "project:ALSysidCmd", xd + 200, yd - 520, params=sp)
        d.connect("signal", ("clock", "y"), ("cmd", "tm"))
        d.connect("signal", ("cmd", "tau_cmd"), ("drv", "tau_cmd"))
        d.connect("signal", ("cmd", "w_cmd"), ("drv", "w_cmd"))
    elif not drive_off:
        d.ref("tzero", "TauZero", "stdlib:sources/Constant", xd + 40, yd - 480, params={"value": "0.0"})
        d.connect("signal", ("tzero", "y"), ("drv", "tau_cmd"))
        d.connect("signal", ("tzero", "y"), ("drv", "w_cmd"))

    # bench AS5048 on the arm (latency, INL and noise identification; the link-1 sensor's INL)
    if spec.get("bench_encoder"):
        d.ref("encb", "EncBench", "project:AS5048", bx[0] + 280, ry[0] - 200,
              params={"lat": fmt(spec["bench_latency"]), "a1": fmt(enc["inl1"][0]), "p1": fmt(enc["inl1"][1]),
                      "a2": fmt(enc["inl1"][2]), "p2": fmt(enc["inl1"][3]), "sigma": fmt(enc["sigma"]), "zero": "0.0", "nrd": "1.0"},
              constants={"sample_period": "0.001"})
        d.ref("nzb", "NoiseBench", "stdlib:sources/Noise", bx[0] + 280, ry[0] - 320, params={"seed": "31", "std": "1.0"},
              constants={"sample_time": "0.001"})
        d.connect("signal", ("nzb", "y"), ("encb", "z"))
        d.connect("signal", ("j1", "qout"), ("encb", "theta"))
        d.connect("signal", ("j1", "qdout"), ("encb", "w"))

    # link angles and energy
    d.ref("angles", "Angles", "project:LinkAngles", 1760, 320)
    d.connect("signal", ("j2", "qout"), ("angles", "q1"))
    d.connect("signal", ("j3", "qout"), ("angles", "q2"))
    d.ref("energy", "Energy", "project:ALEnergy", 1760, 560,
          params={"m": vec(mass), "J_m": fmt(dr.J_m), "L_eq": fmt(dr.L_eq), "R_eq": fmt(dr.R_eq)})
    for k in (1, 2, 3):
        d.connect("signal", (f"b{k}", "V"), ("energy", f"V{k}"))
        d.connect("signal", (f"b{k}", "P"), ("energy", f"P{k}"))
        d.connect("signal", (f"pb{k}", "g"), ("energy", f"g{k}"))
    for src, port in (("wm", "wm"), ("isense", "ie"), ("uoff" if drive_off else "cur", "uq")):
        d.connect("signal", (src, "uq" if src == "cur" else "y"), ("energy", port))
    d.connect("signal", ("spring", "E"), ("energy", "E_gear"))
    d.connect("signal", ("spring", "P"), ("energy", "P_gear"))
    d.connect("signal", ("fin", "P"), ("energy", "P_fin"))
    d.connect("signal", ("fout", "P"), ("energy", "P_fout"))
    d.connect("signal", ("fj2", "P"), ("energy", "P_j1"))
    d.connect("signal", ("fj3", "P"), ("energy", "P_j2"))

    # the push on link 2: a force pulse at its tip, perpendicular to the link in the pendulum plane
    push = spec.get("push", {"force": 0.0, "t": 1000.0, "dur": 0.05})
    tip = pose_params(((1.0, 0.0, 0.0, 0.0), (rg["bodies"][2].c - rg["link_l"], 0.0, 0.0)))
    d.ref("tipt", "TipPoint", "stdlib:multibond/FixedTransform3DNeutral", bx[2] + 360, ry[2] + 230, params=tip)
    d.ref("dist", "Push", "stdlib:multibond/ExternalWrenchSpatial", bx[2] + 520, ry[2] + 230)
    d.ref("pulse", "PushPulse", "stdlib:sources/Pulse", bx[2] + 520, ry[2] + 120,
          params={"amplitude": fmt(push["force"]), "period": "1000.0", "duty": fmt(push["dur"] / 1000.0), "t_start": fmt(push["t"])})
    d.ref("zero", "Zero", "stdlib:sources/Constant", bx[2] + 360, ry[2] + 120, params={"value": "0.0"})
    d.connect("bond", ("dist", "p"), ("tipt", "a"))
    d.connect("bond", ("tipt", "b"), ("bj3", None))
    for port in ("tx", "ty", "tz", "fx", "fz"):
        d.connect("signal", ("zero", "y"), ("dist", port))
    d.connect("signal", ("pulse", "y"), ("dist", "fy"))

    doc = {
        "format": "bgsim.model",
        "language": "0.1.0",
        "name": spec["name"],
        "$comment": spec["comment"],
        "diagram": d.document(),
        "settings": rb.settings(spec["t_end"], spec.get("points", int(spec["t_end"] * 500) + 1),
                                spec.get("reltol", 1e-6), spec.get("abstol", 1e-8)),
        "plots": spec.get("plots", []),
        "scene": {"file": "scenes/actilink.sdf"},
        "parameters": [{"name": "enc_nrd", "value": fmt(spec.get("enc_nrd", 1.0)),
                        "description": "AS5048 reads: EtherCAT cycles per new reading (1 = every cycle)"}],
        "bindings": [{"target": f"joint:{jn}", "property": "position", "signal": sg}
                     for jn, sg in (("arm", "J1/qout"), ("link1", "J2/qout"), ("link2", "J3/qout"))],
    }
    if spec.get("solver"):
        doc["settings"]["solver"] = spec["solver"]
    if spec.get("max_step"):
        doc["settings"]["max_step"] = spec["max_step"]
    if spec.get("dashboard"):
        doc["dashboard"] = spec["dashboard"]
    return doc


