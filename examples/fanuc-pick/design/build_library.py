"""Write the generated project blocks of fanuc-pick (`library/*.jl`).

    uv run examples/fanuc-pick/design/build_library.py

* `PickPlanner`  the 1 kHz planner (trajectory families, IK/FK, timeline, gripper sequence, the
                 gripper twist for the kinematic arm, the use of the datasheet limits), generated
                 from `planner.py`;
* `SphereInBox`, `CylinderInBox`  the contact of a loose sphere / cylinder with the six inner
                 walls of the carton (two-body spatial elements, unrolled per wall);
* `PickMonitor`  holding margin per zone and in total, the held latch;
* `ToolMotion`   the prescribed gripper motion (the kinematic arm): a spatial flow source with a
                 first-order hold of the planner's twist.

`PneumaticCylinder` is hand-written.
"""

from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import params as P  # noqa: E402
import planner  # noqa: E402

LIB = HERE.parent / "library"
NL = "\n"


def _units() -> dict:
    """unit and description of every planner parameter: from the global table."""
    return {name: (unit, desc) for name, _value, unit, desc in P.global_rows()}


def _write(name: str, text: str) -> None:
    LIB.mkdir(exist_ok=True)
    (LIB / f"{name}.jl").write_text(text, encoding="utf-8", newline=NL)
    print("wrote", LIB / f"{name}.jl", text.count(NL), "lines")


def _desc(text: str) -> str:
    return text.replace('"', "'")


def param_lines(names, defaults) -> str:
    units = _units()
    out = []
    for n in names:
        unit, desc = units.get(n, ("1", n))
        out.append(f'        {n}::Real = {defaults[n]!r}, [unit = "{unit}", description = "{_desc(desc)}"]')
    return NL.join(out)


def _value(v) -> str:
    if isinstance(v, (list, tuple)) or getattr(v, "ndim", 0) == 1:
        return "[" + ", ".join(repr(float(x)) for x in v) + "]"
    return repr(float(v))


def planner_block() -> str:
    g = P.global_values()
    head = '''@block PickPlanner begin
    # The pick-and-place planner of fanuc-pick (1 kHz, D28 discrete code). GENERATED by
    # design/build_library.py from design/planner.py: do not edit; the Python reference runs the
    # same formulas (design/planner.py `reference`).
    #
    # Motion of the flange (tool straight down, gripper yaw psi), every move one normalised
    # jerk-limited profile s(tau; alpha, lam):
    #   A -approach-> B (pick contact) -T_seal- -lift S1-> C -transfer S2-> D -lower S3-> E
    #   (place contact) -T_rel- -depart-> F.
    # A move with the time scales V = max L_i/v_i, A = max L_i/a_i/(1 - lam/2), J = max L_i/j_i
    # takes T = V + A/V, alpha = (A/V)/T if V^2 >= A, else T = 2 sqrt(A), alpha = 1/2, stretched
    # to (J jj)^(1/3) when the jerk asks for it (jj the normalised peak jerk of the profile).
    # Families: 1 joint PTP with stops (Cartesian lift/lower), 2 Cartesian with stops, 3 Cartesian
    # blended (the transfer starts when the lift has r_b to go; the lowering r_b-worth of time
    # before the transfer ends), 4 joint blended. IK: closed form for the tool pointing down
    # (q4 = 0, q5 = q2 - q3 - pi/2, q6 = psi - q1).
    #
    # The arm is KINEMATIC: it follows the joint reference exactly. The reference is evaluated at
    # t - Ts, t and t + Ts; the joint rate and acceleration are the central differences, the jerk
    # the backward difference of the acceleration. The gripper pose is the forward kinematics of
    # q; `V`/`Vd` are its body twist and twist rate at the tick `tk` (ToolMotion holds them to
    # first order between the ticks). The datasheet limits (LR-10iA/10 rates, assumed
    # acceleration and jerk, ranges, wrist moment/inertia/payload ratings) are not enforced by a
    # servo but reported: util_* are the running maxima of the planned use in %.
    # Gripper: ue_k (cylinder valve, +1 extend / -1 retract) and uv_k (vacuum) per zone; act (the
    # lip inside the top face at the pick); held (the load is carried, t_lift <= t < t_place).
    @parameters begin
'''
    body = param_lines(planner.PLANNER_PARAMS, g)
    defaults = planner.output_defaults(g)
    outs = [NL + "    end", "    @outputs begin"]
    for name, typ, unit, desc in planner.OUTPUTS:
        u = f'unit = "{unit}", ' if unit else ""
        outs.append(f'        {name}::{typ} = {_value(defaults[name])}, [{u}description = "{_desc(desc)}"]')
    outs += ["    end", "    @discrete Ts = 0.001 begin", ""]
    return head + body + NL.join(outs) + planner.emit_block() + NL + "    end" + NL + "end" + NL


TOOL = '''@block ToolMotion begin
    # The prescribed motion of the gripper frame (the kinematic arm): a spatial flow source whose
    # twist is the planner's body twist `V` at the tick `tk`, held to first order with its rate
    # `Vd` until the next tick,
    #
    #     p.f = V + Vd (t - tk),
    #
    # so the twist is continuous to O(jerk Ts^2) and its integral (the gripper pose seen by the
    # rods and cups) follows the planned path to O(jerk Ts^3) per tick, without the 1 ms
    # staircase of a zero-order hold. GENERATED by design/build_library.py.
    # `W` is the wrench the motion takes (the rods, cups and the load pulling on the flange),
    # in the gripper frame, about the flange: the robot must supply it.
    @ports p::Power{Spatial}
    @inputs begin
        V::Vec{6}, [description = "Body twist at the tick [w; v] (rad/s, m/s)"]
        Vd::Vec{6}, [description = "Rate of the body twist at the tick"]
        tk::Real, [unit = "s", description = "Time of the tick"]
    end
    @outputs W::Vec{6}, [description = "Wrench on the flange [M; F] (N m, N), gripper frame"]
    @equations begin
        for k in 1:6
            p.f[k] ~ V[k] + Vd[k] * (t - tk)
            W[k] ~ p.e[k]
        end
    end
    @causality p => (:flow_out, :fixed)
end
'''


