"""Write the model documents of pendulum-double-fixed (the plant, the controller block, the disturbance).

    uv run examples/pendulum-double-fixed/design/build_model.py
"""

from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from params import CFG, CTRL_BLOCK, EXAMPLE, PLANT  # noqa: E402
from pendulum_model import build_free, build_main, dump, scene_sdf  # noqa: E402

COMMENT_MAIN = (
    "X5.11: a double pendulum on a fixed pivot, driven at the first joint by a DC gearmotor (pendubot type). "
    "Multibond planar bond graph: RigidBody2D links with distributed mass, Revolute2DCompliant joints "
    "(kt = 1e8 N/m converges to the rigid revolute), the drive is stdlib drives/ElectricDrive -> ElasticShaft -> "
    "Gearbox -> joint 1. project:%s swings the chain up along the optimised trajectory (time-varying LQR), "
    "catches it with a 1 kHz LQR and balances; a force pulse at the tip link at t = %g s is the disturbance. "
    "Generated by design/build_model.py; the controller tables come from design/design.py."
) % (CTRL_BLOCK, CFG["t_dist"])
COMMENT_FREE = (
    "The same plant as the main model with the motor terminals at 0 V and a non-trivial start (joint angles %s rad), "
    "used to prove that design/design.py has the plant of the bond graph (free swing, design ODE versus this run)."
) % ", ".join(f"{q:.4f}" for q in CFG["free_q0"])


def main() -> None:
    models = HERE.parent / "models"
    dump(models / f"{EXAMPLE}.bgmodel.json", build_main(PLANT, CFG, CTRL_BLOCK, EXAMPLE, COMMENT_MAIN))
    dump(models / "free.bgmodel.json", build_free(PLANT, CFG, "free", COMMENT_FREE))
    scenes = HERE.parent / "scenes"
    scenes.mkdir(exist_ok=True)
    (scenes / f"{CFG['scene']}.sdf").write_text(scene_sdf(PLANT, EXAMPLE), encoding="utf-8", newline="\n")
    print("wrote", models)


if __name__ == "__main__":
    main()
