"""Generator of the model documents and of the controller library block (X5.11).

Shared by ``pendulum-double-fixed`` and ``pendulum-triple-fixed``: ``build_models`` writes the
bond-graph model with the controller and the disturbance and the controller-free model used for the
design-versus-bond-graph free-swing check; ``write_ctrl_block`` writes ``library/<Block>.jl`` with the
constant tables (the gains, the trajectory and the TVLQR gain schedule) of ``design.py``.
"""

from __future__ import annotations

import json
import math
from pathlib import Path

import numpy as np

from pendulum_common import Plant, Tables

KT_PIVOT = 1.0e8  # pivot translational stiffness of the compliant revolute (N/m)
HALF_PI = math.pi / 2.0


def _n(x: float) -> str:
    return repr(float(x))


def _vec(v) -> str:
    return "[" + ", ".join(f"{float(x):.9g}" for x in v) + "]"


# ------------------------------------------------------------------------------ Julia block


def fmt_table(values) -> str:
    """Round a table the way it is written so that design.py and the block agree to the digit."""
    return [float(f"{v:.9g}") for v in values]


def write_ctrl_block(path: Path, name: str, tab: Tables, n: int, label: str) -> None:
    rows = tab.xs.shape[0]
    nx = 2 * n
    qn = [f"q{k + 1}" for k in range(n)]
    dn = [f"qd{k + 1}" for k in range(n)]
    sn = qn + dn
    L = []
    a = L.append
    a(f"@block {name} begin")
    a(f"    # {label}: swing-up, catch and balance of the fixed-pivot chain, sampled at 1 kHz (D28 firmware).")
    a("    #")
    a("    # Generated by design/design.py: every number below is a constant table of that script.")
    a("    #")
    a("    #   t < t_on                    phase 0, u = 0 (hanging, motor voltage 0)")
    a("    #   t >= t_on, not caught       phase 1, time-varying LQR along the optimised trajectory")
    a("    #                                 u = u_ff(t - t_on) - K(t - t_on) (x - x_ref(t - t_on))")
    a("    #                               the tables hold one row every dt_tab = %g ms; the row weights are the" % (tab.dt * 1e3))
    a("    #                               hat functions of the position in the table, i.e. linear interpolation,")
    a("    #                               and the last row is held beyond the table")
    a("    #   V(x) < V_catch              catch: latched, phase 2, infinite-horizon LQR")
    a("    #                                 u = -K_lqr (x - x_up),  V(x) = (x - x_up)' P_lqr (x - x_up)")
    a("    #")
    a("    # x = [q1 .. qn, qd1 .. qdn] (q1 the absolute angle of link 1 from +x, q2.. relative joint angles),")
    a("    # x_up = [pi/2, 0, .., 0]. The output is the motor terminal voltage, clamped to +-u_max.")
    a("    @constants R::Int = %d" % rows)
    a("    @parameters begin")
    a('        t_on::Real = %s, [unit = "s", description = "Start of the swing-up"]' % _n(tab.t_on))
    a('        dt_tab::Real = %s, [unit = "s", min = 1.0e-9, description = "Spacing of the table rows"]' % _n(tab.dt))
    a('        V_catch::Real = %s, [description = "Catch threshold on V(x), the LQR cost-to-go (x - x_up)T P_lqr (x - x_up)"]' % _n(tab.V_catch))
    a('        u_max::Real = %s, [unit = "V", min = 0, description = "Voltage limit"]' % _n(tab.u_max))
    a("        K_lqr::Vec{%d} = %s, [description = \"Balance gain, u = -K_lqr (x - x_up)\"]" % (nx, _vec(tab.K_lqr)))
    rowsP = "; ".join(" ".join(f"{float(v):.9g}" for v in r) for r in tab.P_lqr)
    a("        P_lqr::Mat{%d,%d} = [%s], [description = \"Riccati matrix of the balance LQR (catch metric)\"]" % (nx, nx, rowsP))
    a("        u_ff::Vec{R} = %s, [unit = \"V\", description = \"Nominal voltage\"]" % _vec(tab.us))
    for j in range(nx):
        a("        xr_%s::Vec{R} = %s, [description = \"Nominal %s\"]" % (sn[j], _vec(tab.xs[:, j]), sn[j]))
    for j in range(nx):
        a("        k_%s::Vec{R} = %s, [description = \"TVLQR gain on %s\"]" % (sn[j], _vec(tab.Ks[:, j]), sn[j]))
    a("    end")
    a("    @inputs begin")
    for nm in sn:
        a(f"        {nm}::Real")
    a("        tm::Real")
    a("    end")
    a("    @outputs begin")
    a('        u::Real = 0.0, [unit = "V"]')
    a('        phase::Real = 0.0, [description = "0 hanging, 1 swing-up, 2 balance"]')
    a('        V::Real = 0.0, [description = "Distance to upright, the LQR cost-to-go (x - x_up)T P_lqr (x - x_up)"]')
    a("    end")
    a("    @variables caught::Int = 0, [description = \"1 once the balance LQR has taken over\"]")
    a("    @discrete Ts = 1e-3 begin")
    xs = ", ".join([f"{qn[0]} - {HALF_PI!r}"] + qn[1:] + dn)
    a(f"        e = [{xs}]")
    a("        Vx = dot(e, P_lqr * e)")
    a("        caught = ifelse(tm >= t_on && (caught == 1 || Vx < V_catch), 1, 0)")
    a("        u_bal = -dot(K_lqr, e)")
    a("        s = clamp((tm - t_on) / dt_tab, 0.0, %s)" % float(rows - 1))
    a("        uf = 0.0")
    for nm in sn:
        a(f"        r_{nm} = 0.0")
        a(f"        g_{nm} = 0.0")
    a("        for k in 1:R")
    a("            w = max(0.0, 1.0 - abs(s - (k - 1)))")
    a("            uf = uf + w * u_ff[k]")
    for nm in sn:
        a(f"            r_{nm} = r_{nm} + w * xr_{nm}[k]")
        a(f"            g_{nm} = g_{nm} + w * k_{nm}[k]")
    a("        end")
    fb = " + ".join(f"g_{nm} * ({nm} - r_{nm})" for nm in sn)
    a(f"        u_sw = uf - ({fb})")
    a("        u_cmd = ifelse(tm < t_on, 0.0, ifelse(caught == 1, u_bal, u_sw))")
    a("        u = clamp(u_cmd, -u_max, u_max)")
    a("        phase = ifelse(tm < t_on, 0.0, ifelse(caught == 1, 2.0, 1.0))")
    a("        V = Vx")
    a("    end")
    a("end")
    path.write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")


# ------------------------------------------------------------------------------ model documents


class Doc:
    def __init__(self) -> None:
        self.nodes: list[dict] = []
        self.conns: list[dict] = []
        self.byname: dict[str, str] = {}
        self._c = 0

    def node(self, name, block, x, y, params=None, starts=None, constants=None):
        nid = f"n{len(self.nodes) + 1:02d}"
        self.byname[name] = nid
        entry = {
            "id": nid,
            "name": name,
            "block": block,
            "position": {"x": x, "y": y},
            "rotation": 0,
            "flipX": False,
            "params": params or {},
            "constants": constants or {},
            "starts": starts or {},
            "ui": {"showLabel": True, "color": None},
        }
        self.nodes.append(entry)
        return nid

    def conn(self, kind, a, b, label=None):
        """a, b: 'Name.port' (port omitted for a junction)."""
        self._c += 1

        def end(s):
            if "." in s:
                nm, port = s.split(".", 1)
                return {"node": self.byname[nm], "port": port}
            return {"node": self.byname[s]}

        self.conns.append({"id": f"c{self._c:02d}", "kind": kind, "from": end(a), "to": end(b), "route": [], "label": label})

    def bond(self, a, b):
        self.conn("bond", a, b)

    def wire(self, a, b):
        self.conn("wire", a, b)

    def sig(self, a, b, label=None):
        self.conn("signal", a, b, label)


def ref(name: str) -> dict:
    return {"ref": name}


def _upright_source(n: int) -> str:
    ins = "\n".join(f"        q{k + 1}::Real" for k in range(n))
    outs = "\n".join(f'        a{k + 1}::Real, [unit = "rad"]' for k in range(n))
    eqs = []
    for k in range(n):
        s = " + ".join(f"q{j + 1}" for j in range(k + 1))
        eqs.append(f"        a{k + 1} ~ {s} - {HALF_PI!r}")
    return (
        "@block Upright begin\n"
        f"    # Absolute angle of every link from the upright (+y) direction: a_k = q1 + ... + qk - pi/2.\n"
        f"    @inputs begin\n{ins}\n    end\n"
        f"    @outputs begin\n{outs}\n    end\n"
        f"    @equations begin\n" + "\n".join(eqs) + "\n    end\nend\n"
    )


def build_plant(d: Doc, P: Plant, q0: list[float], free: bool, d_static: bool, bt: float, x0: float = 80.0) -> None:
    """The bond-graph plant: ground, joints, links, bodies, the pose chain, the drive."""
    n = P.n
    dx = 190.0
    y0 = 320.0
    d.node("Ground", ref("stdlib:multibond/GroundPlanar"), x0, y0)
    mass_below = [sum(P.m[k:]) for k in range(n)]
    for k in range(n):
        xk = x0 + dx * (1 + 2 * k) + 0.0
        starts = {}
        if d_static:
            starts["d"] = _vec([mass_below[k] * P.g / KT_PIVOT, 0.0])
        rx = 0.0 if k == 0 else P.L[k - 1] - P.lc[k - 1]
        d.node(
            f"Joint{k + 1}",
            ref("stdlib:planar/Revolute2DCompliant"),
            xk, y0,
            params={"rx": _n(rx), "ry": "0.0", "kt": _n(KT_PIVOT), "bt": _n(bt), "k": "0.0", "b": _n(P.b[k]),
                    "q0": _n(q0[k]), "qrest": "0.0"},
            starts=starts,
        )
        d.node(f"Link{k + 1}", ref("stdlib:planar/FixedJoint2D"), xk + dx, y0,
               params={"x": _n(P.lc[k]), "y": "0.0", "theta": "0.0"})
        d.node(f"BodyJ{k + 1}", {"junction": "1"}, xk + 2 * dx, y0)
        d.node(f"Body{k + 1}", ref("stdlib:planar/RigidBody2D"), xk + 2 * dx, y0 - 150.0,
               params={"m": _n(P.m[k]), "J": _n(P.J[k]), "g0": _n(P.g)})
        if k == 0:
            d.bond("Ground.p", "Joint1.parent")
        else:
            d.bond(f"Joint{k + 1}.parent", f"BodyJ{k}")
        if k > 0:  # a passive joint: zero torque on the drive port
            d.node(f"Free{k + 1}", ref("stdlib:bondgraph/Se"), xk, y0 - 150.0, params={"e": "0.0"})
            d.bond(f"Free{k + 1}.p", f"Joint{k + 1}.drive")
        d.bond(f"Joint{k + 1}.child", f"Link{k + 1}.parent")
        d.bond(f"Link{k + 1}.child", f"BodyJ{k + 1}")
        d.bond(f"Body{k + 1}.p", f"BodyJ{k + 1}")
    # pose chain (composed, never integrated: D-MB6)
    yp = y0 + 330.0
    for k in range(n):
        xk = x0 + dx * (1 + 2 * k)
        rx = 0.0 if k == 0 else P.L[k - 1] - P.lc[k - 1]
        d.node(f"PoseJ{k + 1}rel" if k else "PoseJ1", ref("stdlib:planar/JointPose2D"), xk, yp,
               params={"rx": _n(rx), "ry": "0.0", "theta0": "0.0"})
        d.sig(f"Joint{k + 1}.qout", (f"PoseJ{k + 1}rel" if k else "PoseJ1") + ".q")
        if k > 0:
            d.node(f"PoseJ{k + 1}", ref("stdlib:multibond/ComposePose2D"), xk + dx, yp)
            d.sig(f"PoseB{k}.g", f"PoseJ{k + 1}.gp")
            d.sig(f"PoseJ{k + 1}rel.g", f"PoseJ{k + 1}.gl")
        d.node(f"CoM{k + 1}", ref("stdlib:planar/LocalPose2D"), xk, yp + 130.0,
               params={"x": _n(P.lc[k]), "y": "0.0", "theta": "0.0"})
        d.node(f"PoseB{k + 1}", ref("stdlib:multibond/ComposePose2D"), xk + dx, yp + 130.0)
        d.sig(f"PoseJ{k + 1}.g", f"PoseB{k + 1}.gp")
        d.sig(f"CoM{k + 1}.g", f"PoseB{k + 1}.gl")
        d.sig(f"PoseB{k + 1}.g", f"Body{k + 1}.g")
    d.node("TipOffset", ref("stdlib:planar/LocalPose2D"), x0 + dx * (2 * n + 1), yp,
           params={"x": _n(P.L[-1]), "y": "0.0", "theta": "0.0"})
    d.node("PoseTip", ref("stdlib:multibond/ComposePose2D"), x0 + dx * (2 * n + 2), yp)
    d.sig(f"PoseJ{n}.g", "PoseTip.gp")
    d.sig("TipOffset.g", "PoseTip.gl")
    # drive: DC motor -> elastic shaft -> gearbox -> joint 1
    yd = y0 - 330.0
    d.node("Motor", ref("stdlib:drives/ElectricDrive"), x0 + dx, yd,
           params={"R_w": _n(P.Rw), "L": _n(P.Lw), "k_t": _n(P.kt), "J_m": _n(P.Jm), "b_m": _n(P.bm)})
    d.node("Shaft", ref("stdlib:rotation/ElasticShaft"), x0 + 2 * dx, yd, params={"k": _n(P.ks), "d": _n(P.ds)})
    d.node("Gear", ref("stdlib:drives/Gearbox"), x0 + 3 * dx, yd, params={"N": _n(P.N)})
    d.wire("Motor.shaft", "Shaft.a")
    d.wire("Shaft.b", "Gear.a")
    d.wire("Gear.b", "Joint1.drive")
    d.node("Upright", {"inline": {"source": _upright_source(n)}}, x0 + dx * (2 * n + 1), yp + 130.0)
    for k in range(n):
        d.sig(f"Joint{k + 1}.qout", f"Upright.q{k + 1}")


def _settings(t_end: float, points: int) -> dict:
    return {
        "t_start": 0.0,
        "t_end": t_end,
        "solver": "auto",
        "reltol": 1e-8,
        "abstol": 1e-10,
        "max_step": None,
        "output": {"mode": "points", "points": points},
        "event_limit": 200000,
    }


def build_main(P: Plant, cfg: dict, ctrl_block: str, name: str, comment: str) -> dict:
    n = P.n
    d = Doc()
    q0 = [-HALF_PI] + [0.0] * (n - 1)
    build_plant(d, P, q0, free=False, d_static=True, bt=cfg["bt"])
    dx = 190.0
    yc = 120.0
    d.node("Clock", ref("stdlib:sources/Time"), 80.0, yc)
    d.node("Ctrl", ref(f"project:{ctrl_block}"), 80.0 + dx * 2, yc + 20.0)
    d.sig("Clock.y", "Ctrl.tm", "time")
    for k in range(n):
        d.sig(f"Joint{k + 1}.qout", f"Ctrl.q{k + 1}")
        d.sig(f"Joint{k + 1}.qdout", f"Ctrl.qd{k + 1}")
    d.sig("Ctrl.u", "Motor.u", "motor voltage")
    # disturbance on the last link: a force pulse F at the tip, perpendicular to the link
    lever = P.L[-1] - P.lc[-1]
    yw = 700.0
    xw = 80.0 + dx * (2 * n)
    d.node("DistForce", ref("stdlib:sources/Pulse"), xw, yw + 130.0,
           params={"amplitude": _n(cfg["F"]), "period": _n(cfg["pulse_period"]),
                   "duty": _n(cfg["pulse_len"] / cfg["pulse_period"]), "t_start": _n(cfg["t_dist"])})
    d.node("DistTorque", ref("stdlib:sources/Pulse"), xw, yw + 260.0,
           params={"amplitude": _n(cfg["F"] * lever), "period": _n(cfg["pulse_period"]),
                   "duty": _n(cfg["pulse_len"] / cfg["pulse_period"]), "t_start": _n(cfg["t_dist"])})
    d.node("DistAxial", ref("stdlib:sources/Constant"), xw, yw + 390.0, params={"value": "0.0"})
    d.node("Hit", ref("stdlib:multibond/ExternalWrenchPlanar"), xw + dx, yw + 130.0)
    d.sig("DistTorque.y", "Hit.wr", "tip force x lever arm")
    d.sig("DistAxial.y", "Hit.wx")
    d.sig("DistForce.y", "Hit.wy", "tip force")
    d.bond("Hit.p", f"BodyJ{n}")
    plots = [
        {"id": "p1", "title": "Link angles from upright", "signals": [f"Upright/a{k + 1}" for k in range(n)]},
        {"id": "p2", "title": "Motor voltage", "signals": ["Ctrl/u"]},
        {"id": "p3", "title": "Controller phase (0 hanging, 1 swing-up, 2 balance)", "signals": ["Ctrl/phase"]},
        {"id": "p4", "title": "Joint rates", "signals": [f"Joint{k + 1}/qdout" for k in range(n)]},
        {"id": "p5", "title": "Tip position", "signals": ["PoseTip/g[2]", "PoseTip/g[3]"]},
        {"id": "p6", "title": "Disturbance force at the tip", "signals": ["DistForce/y"]},
    ]
    return {
        "format": "bgsim.model",
        "language": "0.1.0",
        "name": name,
        "$comment": comment,
        "diagram": {"nodes": d.nodes, "connections": d.conns, "subsystemPorts": [], "annotations": []},
        "settings": _settings(cfg["t_end"], cfg["points"]),
        "plots": plots,
        "scene": {"file": f"scenes/{cfg['scene']}.sdf"},
        "bindings": [{"target": f"joint:joint{k + 1}", "property": "position", "signal": f"Joint{k + 1}/qout"} for k in range(n)],
    }


def build_free(P: Plant, cfg: dict, name: str, comment: str) -> dict:
    n = P.n
    d = Doc()
    build_plant(d, P, list(cfg["free_q0"]), free=True, d_static=False, bt=cfg["bt"])
    d.node("V0", ref("stdlib:sources/Constant"), 80.0 + 190.0 * 2, 120.0, params={"value": "0.0"})
    d.sig("V0.y", "Motor.u", "motor terminals at 0 V")
    plots = [
        {"id": "p1", "title": "Joint angles", "signals": [f"Joint{k + 1}/qout" for k in range(n)]},
        {"id": "p2", "title": "Joint rates", "signals": [f"Joint{k + 1}/qdout" for k in range(n)]},
    ]
    return {
        "format": "bgsim.model",
        "language": "0.1.0",
        "name": name,
        "$comment": comment,
        "diagram": {"nodes": d.nodes, "connections": d.conns, "subsystemPorts": [], "annotations": []},
        "settings": _settings(cfg["free_t_end"], cfg["free_points"]),
        "plots": plots,
    }


def dump(path: Path, doc: dict) -> None:
    path.write_text(json.dumps(doc, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")


# ------------------------------------------------------------------------------------ 3D scene


def scene_sdf(P: Plant, name: str) -> str:
    """The SDF scene: a base with the motor, the links as bars of different colour and the joints."""
    n = P.n
    colors = [("0.25 0.5 0.85 1", 0.032), ("0.35 0.7 0.45 1", 0.026), ("0.9 0.55 0.1 1", 0.020)]
    hub = [0.034, 0.028, 0.022]
    out = []
    a = out.append
    a('<?xml version="1.0"?>')
    a("<!--")
    a(f"  {name} (X5.11): a fixed-pivot pendulum with {n} links in the vertical X-Z plane.")
    a("")
    a("  The model is planar in its x-y plane with gravity along -y. The scene uses the SDF X-Z plane: model x is")
    a("  SDF x, model y is SDF z, and the model's counter-clockwise joint angles are rotations about -Y (rotating +X")
    a("  towards +Z). Joint 1 is the motor-driven pivot at the world origin; its angle q1 is the absolute angle of")
    a("  link 1 from +X (hanging down: -pi/2, upright: +pi/2). Joints 2.. are the passive joints at the end of each")
    a("  link; their angles are relative to the previous link (0: straight). The links are bars of length")
    a("  " + ", ".join(f"{L:g} m" for L in P.L) + " (centre of mass at the middle).")
    a("  Joint k is bound to Joint<k>/qout in the model's bindings.")
    a("-->")
    a('<sdf version="1.9">')
    a(f'  <model name="{name.replace("-", "_")}">')
    a('    <link name="base">')
    a("      <pose>0 0 0 0 0 0</pose>")
    a('      <visual name="motor_housing">')
    a("        <pose>0 -0.07 0 1.5707963 0 0</pose>")
    a("        <geometry><cylinder><radius>0.045</radius><length>0.09</length></cylinder></geometry>")
    a("        <material><diffuse>0.3 0.3 0.34 1</diffuse></material>")
    a("      </visual>")
    a('      <visual name="gearbox">')
    a("        <pose>0 -0.025 0 1.5707963 0 0</pose>")
    a("        <geometry><cylinder><radius>0.032</radius><length>0.02</length></cylinder></geometry>")
    a("        <material><diffuse>0.6 0.6 0.62 1</diffuse></material>")
    a("      </visual>")
    a('      <visual name="column">')
    a("        <pose>0 -0.07 -0.2 0 0 0</pose>")
    a("        <geometry><box><size>0.06 0.06 0.36</size></box></geometry>")
    a("        <material><diffuse>0.45 0.47 0.5 1</diffuse></material>")
    a("      </visual>")
    a('      <visual name="floor">')
    a("        <pose>0 -0.07 -0.39 0 0 0</pose>")
    a("        <geometry><box><size>0.5 0.3 0.02</size></box></geometry>")
    a("        <material><diffuse>0.3 0.3 0.33 1</diffuse></material>")
    a("      </visual>")
    a("    </link>")
    x0 = 0.0
    for k in range(n):
        col, w = colors[k]
        a("")
        a(f'    <link name="link{k + 1}">')
        a(f"      <pose>{x0:g} 0 0 0 0 0</pose>")
        a(f'      <visual name="link{k + 1}_bar">')
        a(f"        <pose>{P.L[k] / 2:g} 0 0 0 0 0</pose>")
        a(f"        <geometry><box><size>{P.L[k]:g} {w:g} {w:g}</size></box></geometry>")
        a(f"        <material><diffuse>{col}</diffuse></material>")
        a("      </visual>")
        a(f'      <visual name="joint{k + 1}_hub">')
        a("        <pose>0 0 0 1.5707963 0 0</pose>")
        a(f"        <geometry><cylinder><radius>{hub[k]:g}</radius><length>{w + 0.02:g}</length></cylinder></geometry>")
        a("        <material><diffuse>0.2 0.2 0.22 1</diffuse></material>")
        a("      </visual>")
        if k == n - 1:
            a('      <visual name="tip_mass">')
            a(f"        <pose>{P.L[k]:g} 0 0 0 0 0</pose>")
            a("        <geometry><sphere><radius>0.022</radius></sphere></geometry>")
            a("        <material><diffuse>0.85 0.15 0.15 1</diffuse></material>")
            a("      </visual>")
        a("    </link>")
        x0 += P.L[k]
    a("")
    # joints: link k+1 is posed at the end of link k, so its joint-1 frame is at x = L_k in the link-k frame
    parent = "base"
    for k in range(n):
        a(f'    <joint name="joint{k + 1}" type="revolute">')
        a(f"      <parent>{parent}</parent>")
        a(f"      <child>link{k + 1}</child>")
        a("      <axis>")
        a("        <xyz>0 -1 0</xyz>")
        a("      </axis>")
