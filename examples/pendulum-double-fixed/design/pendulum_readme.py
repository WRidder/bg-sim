"""README of the fixed-pivot pendulum examples (X5.11), rendered from params.py and results.json."""

from __future__ import annotations

import json
import math
from pathlib import Path

NAMES = {2: "double", 3: "triple"}


def render_readme(prm, measured: dict) -> str:
    P, C = prm.PLANT, prm.CFG
    n = P.n
    ex = prm.EXAMPLE
    kind = NAMES[n]
    res = json.loads((Path(prm.HERE) / "results.json").read_text(encoding="utf-8"))
    free = json.loads((Path(prm.HERE) / "free_max_diff.json").read_text(encoding="utf-8"))["max_diff"]
    t_on, T_s, t_dist, t_end = C["t_on"], C["T_s"], C["t_dist"], C["t_end"]
    lever = P.L[-1] - P.lc[-1]
    m = measured
    L = []
    w = L.append
    w(f"# {ex} — a {kind} pendulum on a fixed pivot: swing-up, catch, balance, recovery")
    w("")
    w(
        f"A planar {kind} pendulum hangs from a fixed pivot (plan 9.x, X5.11). A DC gearmotor drives the first joint only "
        f"(pendubot type), the other {n - 1} joint{'s are' if n > 2 else ' is'} passive. The chain starts hanging at rest with 0 V "
        f"on the motor. At t = {t_on:g} s it swings up along a **trajectory-optimised** feed-forward tracked by a **time-varying LQR**, "
        f"is caught near the upright by an infinite-horizon **LQR** (1 kHz, `@discrete`), balances, and "
        f"{t_dist - res['t_catch']:.1f} s after the catch a {C['pulse_len'] * 1e3:g} ms force pulse of {C['F']:g} N at the tip link is recovered."
    )
    w("")
    w("```")
    w("Clock ─ t ───────────────────────────────┐")
    w(f"Joint1..{n} ─ q, qdot ───────────────────────┼─► Ctrl ({ex.split('-')[1]} swing-up / catch / balance, 1 kHz, ±{P.umax:g} V) ─ u ─► Motor ─ Shaft ─ Gear ─► Joint1")
    w("                                           └─ phase")
    w(f"Ground ─ Joint1 ─ Link1 ─ BodyJ1(Body1) ─ Joint2 ─ Link2 ─ BodyJ2(Body2){' ─ Joint3 ─ Link3 ─ BodyJ3(Body3)' if n == 3 else ''} ◄─ Hit (tip force pulse)")
    w("```")
    w("")
    w("## Plant (multibond bond graph)")
    w("")
    w("| part | block |")
    w("| --- | --- |")
    w("| links | `stdlib:planar/RigidBody2D`, a rod with distributed mass: COM at the middle, $J = mL^2/12$ |")
    w("| joints | `stdlib:planar/Revolute2DCompliant` (`kt` = 1e8 N/m converges to the rigid revolute; the rigid variant is index 3), viscous friction `b`; joint 1 carries the motor, the others a zero `Se` |")
    w("| gravity | inside `RigidBody2D` (`GravityPlanar` on the composed pose) |")
    w("| drive | `stdlib:drives/ElectricDrive` → `stdlib:rotation/ElasticShaft` → `stdlib:drives/Gearbox` → joint 1; the shaft keeps the rotor inertia integral-causal (no W201) |")
    w("| disturbance | `stdlib:multibond/ExternalWrenchPlanar` on the last link's 1-junction, three `Pulse`/`Constant` sources (force and the torque of the tip lever arm) |")
    w(f"| controller | project block `{prm.CTRL_BLOCK}` (`library/{prm.CTRL_BLOCK}.jl`, generated by `design/design.py`) |")
    w("")
    w("Parameters (assumed, no datasheet part):")
    w("")
    w("| link | m [kg] | L [m] | COM [m] | J [kg m²] | b [N m s/rad] |")
    w("| --- | --- | --- | --- | --- | --- |")
    for k in range(n):
        w(f"| {k + 1} | {P.m[k]:g} | {P.L[k]:g} | {P.lc[k]:g} | {P.J[k]:.6g} | {P.b[k]:g} |")
    w("")
    w(
        f"Motor: R = {P.Rw:g} Ω, L = {P.Lw * 1e3:g} mH, k_t = {P.kt:g} N m/A, rotor J_m = {P.Jm:g} kg m²; gear ratio N = {P.N:g} "
        f"(reflected rotor inertia {P.N ** 2 * P.Jm:.3g} kg m²); shaft k = {P.ks:g} N m/rad, d = {P.ds:g} N m s/rad on the motor side; "
        f"supply limit ±{P.umax:g} V (stall torque at the joint {P.N * P.kt * P.umax / P.Rw:.3g} N m)."
    )
    w("")
    w("Angles: `q1` is the absolute angle of link 1 from +x (hanging −π/2, upright +π/2), the other joint angles are relative. The model has an inline block `Upright` with the absolute link angles from upright, `Upright/a1..a" + str(n) + "`, used for plots and checks.")
    w("")
    w("Every bond points from the port into the junction. A reversed bond flips the junction's sign convention, and the plant stops matching its equations (found the hard way while building this example).")
    w("")
    w("## Design (`design/`)")
    w("")
    w("| file | what |")
    w("| --- | --- |")
    w("| `params.py` | plant, scenario, weights |")
    w(f"| `design.py` | the whole flow: CasADi dynamics, direct collocation (Hermite–Simpson, IPOPT), TVLQR, LQR, the catch rule, a sampled-data prediction of the run, writes `library/{prm.CTRL_BLOCK}.jl`, `expected.json`, `results.json` |")
    w("| `build_model.py` | `models/*.bgmodel.json` and `scenes/*.sdf` |")
    w("| `build_docs.py` | the source of the model docs (`tools/example_docs`) |")
    w("| `pendulum_*.py` | shared code (the triple imports it from `pendulum-double-fixed/design`) |")
    w("")
    w("```")
    w(f"uv run examples/{ex}/design/build_model.py")
    w(f"uv run examples/{ex}/design/design.py")
    w(f"uv run examples/{ex}/design/design.py --compare run.npz     # model `free` run vs the design ODE")
    w("```")
    w("")
    w(
        f"Trajectory: {C['nk']} Hermite–Simpson intervals over T_s = {T_s:g} s, |u| ≤ {C['u_to']:g} V, cost ∫(u/u_lim)² dt. "
        f"TVLQR and LQR weights Q = diag({', '.join(f'{float(C['Q'][i][i]):g}' for i in range(2 * n))}), R = {C['R']:g}. "
        f"Catch rule: V(x) = (x−x_up)ᵀ P (x−x_up) < {res['V_catch']:g}. LQR K = {', '.join(f'{k:.4g}' for k in res['K_lqr'])}."
    )
    w("")
    w("## Measured")
    w("")
    w("| quantity | value |")
    w("| --- | --- |")
    w(f"| design model vs bond graph, free swing (3 s, max over joints) | {free:.2e} rad |")
    w(f"| swing-up | starts {t_on:g} s, trajectory time {T_s:g} s |")
    w(f"| catch (phase 2) | {m['t_catch']:.3f} s |")
    w(f"| upright band before the disturbance (all links) | {m['band_deg']:.4f} deg |")
    w(f"| disturbance | {C['F']:g} N, {C['pulse_len'] * 1e3:g} ms at {t_dist:g} s |")
    w("| peak deflection after it | " + ", ".join(f"link {k + 1}: {v:.2f} deg" for k, v in enumerate(m["peak_deg"])) + " |")
    w(f"| recovery (all links inside 1 deg) | {m['recovered']:.3f} s, {m['recovered'] - t_dist:.2f} s after the pulse starts |")
    w(f"| peak motor voltage | {m['peak_u']:.3f} V of {P.umax:g} V |")
    w(f"| compile + run (real worker) | {m['time_s']:.0f} s (of which the run {m['run_s']:.0f} s), {m['points']} output rows |")
    w("")
    w(f"The prediction of `design.py` (CVODES on the non-linear model with the winding current, the same tables) agrees with the bond-graph run to {m['pred_diff']:.1e} rad in every link angle.")
    w("")
    w("## Checks")
    w("")
    w(f"`uv run examples/run_checks.py --only {ex}` runs `expected.json`: hanging at rest before t_on, the phases and the catch time, upright by t_on + T_s within 0.2 deg until the disturbance, the disturbance peaks (5 %), recovery, the voltage within the supply, the free swing against the design ODE, the 3D forward kinematics from the joint bindings against the composed poses, no diagnostics. The docs of the model (`models/{ex}.docs`) are linted by the same command. Browser acceptance: `web/tests/e2e/pendulum-fixed.spec.ts` (real worker).")
    w("")
    w("## 3D")
    w("")
    w(f"`scenes/{ex}.sdf`: a base with the motor and the gearbox, {n} bars of different length and colour, hubs at the joints and a red tip mass. Joint `joint<k>` is bound to `Joint<k>/qout`.")
    w("")
    return "\n".join(L) + "\n"
